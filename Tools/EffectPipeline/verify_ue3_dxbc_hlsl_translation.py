#!/usr/bin/env python3
"""Prove a translated family HLSL reproduces its cooked DXBC numerically.

A translation that compiles is not a translation that is correct.  This
harness closes that gap the only way it can be closed without the original
renderer: it runs the cooked pixel shader and the compiled translation on the
same WARP device, with the same constant buffers, the same textures, the same
samplers and the same carrier vertex shader, and compares every render target
the program writes.

The fixture values are synthetic and deterministic.  They are chosen to
exercise the arithmetic program, not to reproduce a material instance.  The
current texture fixtures are uniform 1x1 resources, so a pass does not prove
UV, LOD, address-mode, or TextureCube sampling semantics.  It means only that
the exercised translation computes what the cooked program computes; sampler
state, vertex factory, render state and visual fidelity remain separate gates.
"""

