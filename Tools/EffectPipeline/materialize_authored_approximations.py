def _require_object(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be an object.")
    return value


def _require_array(value: Any, label: str) -> list[Any]:
    if not isinstance(value, list):
        raise ValueError(f"{label} must be an array.")
    return value


def _require_string(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value or len(value) > 1024:
        raise ValueError(f"{label} must be a non-empty bounded string.")
    return value


def _require_int(value: Any, label: str, *, positive: bool = False) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError(f"{label} must be an integer.")
    if positive and value <= 0:
        raise ValueError(f"{label} must be positive.")
    return value


def _require_number(
    value: Any,
    label: str,
    *,
    non_negative: bool = False,
    positive: bool = False,
) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{label} must be a number.")
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{label} must be finite.")
    if non_negative and result < 0.0:
        raise ValueError(f"{label} must not be negative.")
    if positive and result <= 0.0:
        raise ValueError(f"{label} must be positive.")
    return result


def _load_json(path: Path, label: str) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as stream:
            return _require_object(json.load(stream), label)
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"{label} could not be parsed: {error}") from error


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _resolve_under(
    root: Path,
    value: Any,
    label: str,
    *,
    require_file: bool,
) -> Path:
    relative = _require_string(value, label).replace("\\", "/")
    if relative.startswith("/") or ":" in relative or ".." in relative.split("/"):
        raise ValueError(f"{label} escaped its root.")
    path = (root / relative).resolve()
    try:
        path.relative_to(root)
    except ValueError as error:
        raise ValueError(f"{label} escaped its root.") from error
    if require_file and not path.is_file():
        raise ValueError(f"{label} does not exist: {path}")
    return path


def _resolve_data_path(value: Any, label: str, *, require_file: bool) -> Path:
    relative = _require_string(value, label).replace("\\", "/")
    if relative.startswith("Data/"):
        relative = relative[len("Data/") :]
    return _resolve_under(DATA_ROOT, relative, label, require_file=require_file)


def _data_relative(path: Path) -> str:
    return path.resolve().relative_to(DATA_ROOT).as_posix()


def _validate_hash(path: Path, expected: Any, label: str) -> str:
    expected_hash = _require_string(expected, label)
    if len(expected_hash) != 64 or any(
        character not in "0123456789abcdef" for character in expected_hash
    ):
        raise ValueError(f"{label} is not a lowercase SHA-256.")
    actual_hash = _sha256_file(path)
    if actual_hash != expected_hash:
        raise ValueError(
            f"Source evidence changed after intake: {path}; "
            f"expected={expected_hash} actual={actual_hash}"
        )
    return actual_hash


def _validate_resource_asset_id(value: Any, label: str) -> str:
    asset_id = _require_string(value, label)
    normalized = asset_id.replace("\\", "/")
    if (
        normalized != asset_id
        or not asset_id.startswith("Effect/")
        or ":" in asset_id
        or ".." in asset_id.split("/")
    ):
        raise ValueError(f"{label} is not a Resources-relative Effect asset ID.")
    path = (RESOURCES_ROOT / asset_id).resolve()
    try:
        path.relative_to(RESOURCES_ROOT)
    except ValueError as error:
        raise ValueError(f"{label} escaped the Resources root.") from error
    if not path.is_file():
        raise ValueError(f"{label} is unresolved: {asset_id}")
    return asset_id


def _validate_element_resources(
    element: dict[str, Any], source_kind: str, source_element_id: str
) -> list[dict[str, str]]:
    resources: list[dict[str, str]] = []
    seen_slots: set[str] = set()
    for index, raw_resource in enumerate(
        _require_array(element.get("resources"), "source resources")
    ):
        resource = _require_object(raw_resource, f"source resources[{index}]")
        slot_id = _require_string(resource.get("slotId"), "source resource slotId")
        if slot_id not in RESOURCE_SLOTS or slot_id in seen_slots:
            raise ValueError(
                f"Source Element has an invalid resource slot: {source_element_id}"
            )
        seen_slots.add(slot_id)
        resources.append(
            {
                "slotId": slot_id,
                "assetId": _validate_resource_asset_id(
                    resource.get("assetId"), f"source resource {slot_id}"
                ),
            }
        )
    if source_kind in {"standaloneMesh", "meshParticle"}:
        if "meshModel" not in seen_slots:
            raise ValueError(f"Mesh source has no meshModel: {source_element_id}")
    elif source_kind in {"standaloneSprite", "spriteParticle"}:
        if "meshModel" in seen_slots or not (
            {"base", "noise", "mask", "emissive", "dissolve"} & seen_slots
        ):
            raise ValueError(
                f"Sprite source has no resolved texture carrier: {source_element_id}"
            )
    return resources


def _resource_binding_evidence(
    resources: list[dict[str, str]], source_element_id: str
) -> list[dict[str, Any]]:
    evidence: list[dict[str, Any]] = []
    for source_order, resource in enumerate(resources):
        slot_id = _require_string(resource.get("slotId"), "drawable resource slotId")
        asset_id = _validate_resource_asset_id(
            resource.get("assetId"), f"drawable resource {slot_id}"
        )
        resource_path = (RESOURCES_ROOT / asset_id).resolve()
        evidence.append(
            {
                "sourceOrder": source_order,
                "slotId": slot_id,
                "assetId": asset_id,
                "resourceSha256": _sha256_file(resource_path),
                "sourceElementId": source_element_id,
            }
        )
    return evidence


def _model_info_evidence(model_resource: dict[str, Any]) -> dict[str, Any]:
    """Prove that a no-Base source model cannot supply an embedded Base texture."""

    if model_resource.get("slotId") != "meshModel":
        raise ValueError("Model info evidence requires a meshModel resource.")
    asset_id = _validate_resource_asset_id(
        model_resource.get("assetId"), "model info meshModel assetId"
    )
    model_path = (RESOURCES_ROOT / asset_id).resolve()
    model_sha256 = _sha256_file(model_path)
    if not MODEL_INFO_TOOL.is_file():
        raise ValueError(f"ModelAssetConverter info tool is missing: {MODEL_INFO_TOOL}")
    tool_sha256 = _sha256_file(MODEL_INFO_TOOL)
    cache_key = (str(model_path), model_sha256, tool_sha256)
    cached = _MODEL_INFO_EVIDENCE_CACHE.get(cache_key)
    if cached is not None:
        return copy.deepcopy(cached)

    try:
        completed = subprocess.run(
            [str(MODEL_INFO_TOOL), "info", str(model_path)],
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=10.0,
        )
    except (OSError, subprocess.SubprocessError) as error:
        raise ValueError(f"ModelAssetConverter info failed for {asset_id}: {error}") from error
    if completed.returncode != 0:
        error_text = (completed.stderr or completed.stdout).strip()
        raise ValueError(
            f"ModelAssetConverter info rejected {asset_id}: exit={completed.returncode} "
            f"message={error_text[:512]}"
        )

    normalized_output = completed.stdout.replace("\r\n", "\n").replace("\r", "\n")
    model_match = re.search(
        r"^\[Model\]\s+sections=(\d+)\s+animations=(\d+)\s+skeleton=(yes|no)\s*$",
        normalized_output,
        flags=re.MULTILINE,
    )
    material_match = re.search(
        r"^\s*material-version=(\d+)\s+count=(\d+)\s*$",
        normalized_output,
        flags=re.MULTILINE,
    )
    first_match = re.search(
        r"^\s*first=(.*?)\s+base=(.*?)\s+normal=(.*?)\s+specular=(.*?)\s+"
        r"emissive=(.*?)\s+orm=(.*?)\s*$",
        normalized_output,
        flags=re.MULTILINE,
    )
    if model_match is None or material_match is None:
        raise ValueError(f"ModelAssetConverter info output is incomplete for {asset_id}.")
    material_count = int(material_match.group(2))
    if material_count > 0 and first_match is None:
        raise ValueError(
            f"ModelAssetConverter did not report the first material for {asset_id}."
        )
    first_material_name = first_match.group(1).strip() if first_match else ""
    first_base_texture = first_match.group(2).strip() if first_match else ""
    if first_base_texture:
        raise ValueError(
            "No-Base Mesh approximation was requested even though ModelAssetConverter "
            f"reported an embedded Base texture: {asset_id} -> {first_base_texture}"
        )
    try:
        tool_path = MODEL_INFO_TOOL.relative_to(REPOSITORY_ROOT.resolve()).as_posix()
    except ValueError:
        tool_path = str(MODEL_INFO_TOOL)
    evidence = {
        "decision": "embeddedFirstBaseTextureAbsent",
        "modelAssetId": asset_id,
        "modelResourceSha256": model_sha256,
        "toolPath": tool_path,
        "toolSha256": tool_sha256,
        "command": "info",
        "normalizedOutputSha256": hashlib.sha256(
            normalized_output.encode("utf-8")
        ).hexdigest(),
        "sectionCount": int(model_match.group(1)),
        "animationCount": int(model_match.group(2)),
        "skeletonPresent": model_match.group(3) == "yes",
        "materialVersion": int(material_match.group(1)),
        "materialCount": material_count,
        "firstMaterialName": first_material_name,
        "firstBaseTexture": "",
        "embeddedFirstBaseTexturePresent": False,
    }
    _MODEL_INFO_EVIDENCE_CACHE[cache_key] = copy.deepcopy(evidence)
    return evidence


def _source_group_texture_bindings(
    source_elements: list[dict[str, Any]],
    *,
    source_document_sha256: str,
    source_effect_asset_id: str,
) -> dict[str, list[dict[str, Any]]]:
    """Index only resolved texture carriers from one exact Imported document."""

    document_sha256 = _require_sha256(
        source_document_sha256, "source group texture document SHA-256"
    )
    effect_asset_id = _require_string(
        source_effect_asset_id, "source group texture Effect asset ID"
    )
    result: dict[str, list[dict[str, Any]]] = {}
    for source_element_order, element in enumerate(source_elements):
        source_element_id = _require_string(
            element.get("id"), "source group texture Element ID"
        )
        source_group_id = element.get("groupId")
        if not isinstance(source_group_id, str) or not source_group_id:
            continue
        raw_resources = element.get("resources")
        if not isinstance(raw_resources, list):
            continue
        source_element_sha256 = strict_materializer.source_element_sha256(element)
        for source_resource_order, raw_resource in enumerate(raw_resources):
            if not isinstance(raw_resource, dict):
                continue
            slot_id = raw_resource.get("slotId")
            if slot_id not in TEXTURE_RESOURCE_SLOTS:
                continue
            try:
                asset_id = _validate_resource_asset_id(
                    raw_resource.get("assetId"),
                    "source group texture carrier assetId",
                )
            except ValueError:
                # Unresolved or malformed rows cannot become an executable donor.
                continue
            resource_path = (RESOURCES_ROOT / asset_id).resolve()
            result.setdefault(source_group_id, []).append(
                {
                    "sourceDocumentSha256": document_sha256,
                    "sourceEffectAssetId": effect_asset_id,
                    "sourceGroupId": source_group_id,
                    "sourceElementId": source_element_id,
                    "sourceElementOrder": source_element_order,
                    "sourceElementSha256": source_element_sha256,
                    "sourceResourceOrder": source_resource_order,
                    "slotId": slot_id,
                    "assetId": asset_id,
                    "resourceSha256": _sha256_file(resource_path),
                }
            )
    return result


def _standalone_drawable_resource_decision(
    element: dict[str, Any],
    renderer_kind: str,
    resources: list[dict[str, str]],
    material_decision: str,
    group_texture_bindings: dict[str, list[dict[str, Any]]],
) -> dict[str, Any]:
    source_element_id = _require_string(element.get("id"), "drawable source Element ID")
    source_evidence = _resource_binding_evidence(resources, source_element_id)
    source_slots = [row["slotId"] for row in source_evidence]
    target_resources = copy.deepcopy(resources)
    detail = _require_object(element.get("detail"), "drawable source detail")
    mesh_detail = _require_object(detail.get("mesh"), "drawable source mesh detail")
    common = {
        "sourceResourceBindings": source_evidence,
        "sourceResourceBindingsSha256": strict_materializer.source_element_sha256(
            resources
        ),
        "sourceSlots": source_slots,
        "sourceUseModelMaterial": mesh_detail.get("useModelMaterial") is True,
        "sourceMeshDetailSha256": strict_materializer.source_element_sha256(
            mesh_detail
        ),
    }
    if renderer_kind == "mesh":
        model = next(
            (row for row in source_evidence if row["slotId"] == "meshModel"), None
        )
        if model is None:
            raise ValueError("Standalone Mesh drawable decision has no meshModel.")
        has_base = "base" in source_slots
        if has_base:
            decision = {
                **common,
                "decision": "meshElementMaterialBasePreserved",
                "disposition": "sourceResourcePreserved",
                "modelResource": copy.deepcopy(model),
                "targetUseModelMaterial": False,
                "targetResourceBindings": target_resources,
                "rationale": (
                    "The resolved source Base texture remains the executable standalone "
                    "Mesh material input."
                ),
            }
        else:
            source_group_id = _require_string(
                element.get("groupId"), "no-Base Mesh source groupId"
            )
            group_carriers = group_texture_bindings.get(source_group_id, [])
            own_carriers = [
                row
                for row in group_carriers
                if row.get("sourceElementId") == source_element_id
            ]
            carrier_scope = "sourceElement" if own_carriers else "sourceCascadeGroup"
            carrier = own_carriers[0] if own_carriers else (
                group_carriers[0] if group_carriers else None
            )
            if carrier is None:
                raise ValueError(
                    "Standalone no-Base Mesh has no resolved texture carrier in its "
                    f"source Element or exact Cascade group: {source_element_id}"
                )
            target_resources.append(
                {"slotId": "base", "assetId": carrier["assetId"]}
            )
            model_info = _model_info_evidence(model)
            runtime_preflight = {
                "result": "executableBaseOverride",
                "rendererPath": "Effect_DocumentRenderer.Mesh.BaseOverride",
                "targetUseModelMaterial": False,
                "baseResource": {
                    "slotId": "base",
                    "assetId": carrier["assetId"],
                },
                "baseResourceSha256": carrier["resourceSha256"],
            }
            decision = {
                **common,
                "decision": (
                    "acceptedElementTextureApproximation"
                    if carrier_scope == "sourceElement"
                    else "acceptedGroupTextureApproximation"
                ),
                "disposition": "acceptedApproximation",
                "modelResource": copy.deepcopy(model),
                "sourceGroupId": source_group_id,
                "carrierScope": carrier_scope,
                "deterministicSelectionPriority": copy.deepcopy(
                    list(MESH_TEXTURE_SELECTION_PRIORITY)
                ),
                "promotedSourceResource": copy.deepcopy(carrier),
                "modelInfoEvidence": model_info,
                "runtimeDrawablePreflight": runtime_preflight,
                "targetUseModelMaterial": False,
                "targetResourceBindings": target_resources,
                "rationale": (
                    "The source Mesh has no Base binding and ModelAssetConverter proves "
                    "that its exact meshModel has no embedded first-material Base texture. "
                    "The first resolved texture is therefore selected deterministically "
                    "from the same source Element, then the exact same Cascade group, and "
                    "aliased to Base. No cross-group, cross-skill, external, or placeholder "
                    "resource is admitted."
                ),
            }
    elif renderer_kind == "sprite":
        base = next((row for row in source_evidence if row["slotId"] == "base"), None)
        if base is not None:
            decision = {
                **common,
                "decision": "spriteBaseResourcePreserved",
                "disposition": "sourceResourcePreserved",
                "baseResource": copy.deepcopy(base),
                "targetUseModelMaterial": False,
                "targetResourceBindings": target_resources,
                "rationale": (
                    "The resolved source Base texture remains the executable standalone "
                    "Sprite carrier."
                ),
            }
        elif material_decision == "sourceMaterialPreserved":
            decision = {
                **common,
                "decision": "sourceMaterialDrawableContractPreserved",
                "disposition": "sourceResourcePreserved",
                "targetUseModelMaterial": False,
                "targetResourceBindings": target_resources,
                "rationale": (
                    "The executable source Material profile owns this Sprite drawable "
                    "contract, so its semantic texture slots remain unchanged."
                ),
            }
        else:
            carrier = next(
                (
                    row
                    for row in source_evidence
                    if row["slotId"]
                    in {"noise", "mask", "emissive", "dissolve"}
                ),
                None,
            )
            if carrier is None:
                raise ValueError(
                    "Standalone Sprite drawable decision has no source texture carrier."
                )
            target_resources.append(
                {"slotId": "base", "assetId": carrier["assetId"]}
            )
            decision = {
                **common,
                "decision": "acceptedSourceTextureBaseAlias",
                "disposition": "acceptedApproximation",
                "promotedSourceResource": copy.deepcopy(carrier),
                "targetUseModelMaterial": False,
                "targetResourceBindings": target_resources,
                "rationale": (
                    "The source Sprite has no Base binding. Its first resolved source-order "
                    "texture carrier is aliased to Base while the original slot remains "
                    "present; no generic texture or cross-skill resource is introduced."
                ),
            }
    else:
        raise ValueError("Standalone drawable decision has unsupported renderer kind.")
    decision["targetResourceBindingsSha256"] = (
        strict_materializer.source_element_sha256(
            decision["targetResourceBindings"]
        )
    )
    return decision


def _validate_source_material(
    element: dict[str, Any], source_element_id: str
) -> tuple[str, dict[str, Any]]:
    material = _require_object(element.get("material"), "source material")
    _require_string(material.get("templateId"), "source material templateId")
    _require_string(material.get("sourceMaterialPath"), "source material path")
    _require_string(material.get("renderProfile"), "source material renderProfile")
    source_profile = _require_object(
        material.get("sourceProfile"), "source material sourceProfile"
    )
    profile_enabled = source_profile.get("enabled") is True
    runtime_profile_value = source_profile.get("runtimeShaderProfileId", "")
    runtime_profile = (
        runtime_profile_value if isinstance(runtime_profile_value, str) else ""
    )
    semantic_status_value = source_profile.get("semanticStatus", "")
    semantic_status = (
        semantic_status_value if isinstance(semantic_status_value, str) else ""
    )
    requires_standard_approximation = (
        not profile_enabled
        or not runtime_profile
        or runtime_profile == FALLBACK_BLOCKED_RUNTIME_PROFILE
        or semantic_status.casefold()
        in {"", "unresolved", "unsupported", "missing_resource"}
    )
    has_unbound_source_texture = False
    raw_textures = source_profile.get("textures", [])
    if not isinstance(raw_textures, list):
        raw_textures = []
        requires_standard_approximation = True
    for texture_index, raw_texture in enumerate(raw_textures):
        texture = _require_object(
            raw_texture, f"source material textures[{texture_index}]"
        )
        source_object_path = texture.get("sourceObjectPath")
        if not isinstance(source_object_path, str) or not source_object_path:
            has_unbound_source_texture = True
        texture_asset_id = texture.get("assetId")
        if texture_asset_id in (None, ""):
            # The executable carrier resources are validated independently and
            # must all resolve.  An unbound UE material parameter is retained as
            # raw provenance and forces the explicit standard-material decision;
            # it is never silently treated as a resolved source texture.
            has_unbound_source_texture = True
        else:
            _validate_resource_asset_id(
                texture_asset_id,
                f"source material textures[{texture_index}].assetId",
            )
    decision = (
        "acceptedStandardApproximation"
        if (
            requires_standard_approximation
            or has_unbound_source_texture
        )
        else "sourceMaterialPreserved"
    )
    return decision, copy.deepcopy(material)


def _conversion_contract(
    source_element: dict[str, Any],
    analysis: dict[str, Any],
    *,
    reviewed_renderer_approximation: bool = False,
) -> tuple[str, list[str], list[dict[str, str]], list[dict[str, str]]]:
    eligibility = analysis["conversionEligibility"]
    if eligibility == strict_materializer.UNKNOWN and not reviewed_renderer_approximation:
        raise ValueError("UNKNOWN source conversion eligibility is not selectable.")
    source_document_kind = analysis["sourceDocumentKind"]
    if source_document_kind != "particle":
        return "sourceStandalonePreserved", [], [], []
    if reviewed_renderer_approximation:
        if eligibility != strict_materializer.UNKNOWN:
            raise ValueError(
                "reviewedRendererApproximation may admit only reviewed UNKNOWN evidence."
            )
        conversion_decision = "reviewedRendererApproximation"
    elif eligibility == strict_materializer.PARTICLE_REQUIRED:
        conversion_decision = "reviewedStandaloneApproximation"
    elif eligibility == strict_materializer.CERTIFIED:
        conversion_decision = "certifiedSingletonStandaloneConversion"
    else:
        raise ValueError(f"Unsupported conversion eligibility: {eligibility}")

    source_recipe = _require_object(
        source_element.get("sourceRecipe"), "source sourceRecipe"
    )
    dispositions: list[dict[str, str]] = []
    module_evidence: list[dict[str, str]] = []
    source_module_ids: list[str] = []
    seen_ids: set[str] = set()
    for index, raw_module in enumerate(
        _require_array(source_recipe.get("modules"), "source sourceRecipe.modules")
    ):
        module = _require_object(raw_module, f"source module[{index}]")
        stable_id = _require_string(
            module.get("stableId"), f"source module[{index}].stableId"
        )
        if stable_id in seen_ids:
            raise ValueError(f"Duplicate source module stableId: {stable_id}")
        seen_ids.add(stable_id)
        source_module_ids.append(stable_id)
        class_name = _require_string(
            module.get("className"), f"source module[{index}].className"
        )
        module_evidence.append(
            {
                "sourceModuleStableId": stable_id,
                "sourceModuleClassName": class_name,
                "sourceModuleSha256": strict_materializer.source_element_sha256(
                    module
                ),
            }
        )
        dispositions.append(
            {
                "sourceModuleStableId": stable_id,
                "sourceModuleClassName": class_name,
                "disposition": "acceptedApproximation",
                "rationale": APPROXIMATION_RATIONALE,
            }
        )
    if not dispositions:
        raise ValueError("Particle conversion has no source module evidence.")
    return conversion_decision, source_module_ids, dispositions, module_evidence


def _safe_float(value: Any, default: float = 0.0) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return default
    result = float(value)
    return result if math.isfinite(result) else default


def _source_class_matches(class_name: str, base_class: str) -> bool:
    """Mirror Effect_Playback.cpp's SourceClass_Matches alias contract."""
    folded = class_name.casefold()
    if folded.startswith("efparticlemodule"):
        folded = folded[2:]
    if folded.endswith("_seeded"):
        folded = folded[:-7]
    return folded == base_class.casefold()


def _distribution_values(
    distribution: dict[str, Any], label: str
) -> list[float]:
    lookup = _require_array(distribution.get("lookupTable"), f"{label}.lookupTable")
    raw_values = lookup
    if not raw_values:
        raw_values = _require_array(
            distribution.get("defaultMinimum"), f"{label}.defaultMinimum"
        ) + _require_array(
            distribution.get("defaultMaximum"), f"{label}.defaultMaximum"
        )
    values: list[float] = []
    for index, value in enumerate(raw_values):
        values.append(_require_number(value, f"{label} value[{index}]"))
    return values


