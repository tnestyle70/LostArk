def _accepted_material(
    source_material: dict[str, Any],
    material_decision: str,
    resources: list[dict[str, str]],
) -> dict[str, Any]:
    material = copy.deepcopy(source_material)
    if material_decision != "acceptedStandardApproximation":
        return material
    material["templateId"] = "effect.standard"
    _require_string(material.get("sourceMaterialPath"), "accepted sourceMaterialPath")
    # This is an executable standard material, not a reconstructed UE3 source
    # profile.  Keeping the raw profile enabled would make the publisher treat
    # approximation provenance as a runtime shader contract.  The immutable raw
    # profile remains hash-pinned in receipt.materialProvenance instead.
    material["sourceProfile"] = {"enabled": False}
    return material


def _copy_selected_element(
    source_element: dict[str, Any],
    candidate: dict[str, Any],
    *,
    target_effect_id: str,
    source_effect_id: str,
    stage_start: float,
    occurrence_index: int,
    renderer_kind: str,
    renderer_rank: int,
) -> dict[str, Any]:
    element = copy.deepcopy(source_element)
    group_id = f"authored.approx.s{occurrence_index + 1:03d}"
    role = f"{renderer_kind}{renderer_rank + 1:02d}"
    element_id = f"{group_id}.{role}"
    element["id"] = element_id
    element["displayName"] = element_id
    element["groupId"] = group_id
    element["sourceNode"] = (
        f"authored-approximation:{target_effect_id}|source:{source_effect_id}"
        f"|element:{candidate['sourceElementId']}"
    )
    element["visible"] = True
    element["kind"] = renderer_kind
    drawable_resource_decision = _require_object(
        candidate.get("standaloneDrawableResourceDecision"),
        "standalone drawable resource decision",
    )
    element["resources"] = copy.deepcopy(
        _require_array(
            drawable_resource_decision.get("targetResourceBindings"),
            "standalone target resource bindings",
        )
    )
    element["material"] = _accepted_material(
        candidate["materialProvenance"],
        candidate["materialDecision"],
        candidate["resources"],
    )
    element["actionCueAttachment"] = {
        "enabled": True,
        "follow": False,
        "sourceAnchorSlotId": "root",
        "runtimeAnchorSlotId": "root",
        "runtimeBoneName": "",
        "socketLocalTransform": {
            "position": [0.0, 0.0, 0.0],
            "rotationDegrees": [0.0, 0.0, 0.0],
            "scale": [1.0, 1.0, 1.0],
        },
    }
    detail = _require_object(element.get("detail"), "source detail")
    timing = _require_object(detail.get("timing"), "source timing")
    source_delay = _require_number(
        timing.get("startDelaySeconds"), "source timing", non_negative=True
    )
    local_delay = source_delay - stage_start
    if local_delay < -TIMELINE_EPSILON:
        raise ValueError("Selected source Element precedes its stage timeline.")
    lifetime_decision = _require_object(
        candidate.get("standaloneLifetimeDecision"),
        "standalone lifetime decision",
    )
    target_start_offset = _require_number(
        lifetime_decision.get("targetStartDelayOffsetSeconds"),
        "standalone target start delay offset",
        non_negative=True,
    )
    timing["startDelaySeconds"] = max(0.0, local_delay) + target_start_offset
    timing["lifeTimeSeconds"] = _require_number(
        lifetime_decision.get("targetLifeTimeSeconds"),
        "standalone target lifetime",
        positive=True,
    )
    size_decision = _require_object(
        candidate.get("standaloneSizeDecision"), "standalone size decision"
    )
    transform = _require_object(detail.get("transform"), "standalone transform")
    transform["scale"] = copy.deepcopy(
        _require_array(size_decision.get("targetStartScale"), "target start scale")
    )
    linear_lerp = _require_object(
        detail.get("linearLerp"), "standalone linearLerp"
    )
    linear_lerp["scale"] = size_decision.get("targetLinearLerpScaleEnabled") is True
    linear_lerp["endScale"] = copy.deepcopy(
        _require_array(size_decision.get("targetEndScale"), "target end scale")
    )
    sprite = _require_object(detail.get("sprite"), "source sprite detail")
    mesh = _require_object(detail.get("mesh"), "source mesh detail")
    if renderer_kind == "mesh":
        sprite["billboard"] = False
        sprite["billboardRollDegrees"] = 0.0
        mesh["useModelMaterial"] = (
            drawable_resource_decision.get("targetUseModelMaterial") is True
        )
    else:
        sprite["billboard"] = True
        sprite["billboardRollDegrees"] = SPRITE_BILLBOARD_ROLL_DEGREES
        mesh["useModelMaterial"] = False
    element["sourceRecipe"] = _reset_source_recipe()
    element["sourcePresentation"] = _reset_source_presentation()
    return element


def _validate_source_document(
    source: dict[str, Any], expected_effect_id: str
) -> list[dict[str, Any]]:
    if (
        source.get("schema") != "lostark.effect-authoring"
        or source.get("version") != 12
        or source.get("effectAssetId") != expected_effect_id
    ):
        raise ValueError("Imported source Effect document contract is invalid.")
    _require_object(source.get("particleSystem"), "source particleSystem")
    elements = [
        _require_object(raw_element, "source element")
        for raw_element in _require_array(source.get("elements"), "source elements")
    ]
    seen_ids: set[str] = set()
    for element in elements:
        element_id = _require_string(element.get("id"), "source element ID")
        if element_id in seen_ids:
            raise ValueError(f"Imported source has duplicate Element ID: {element_id}")
        seen_ids.add(element_id)
    return elements


def _stage_timeline(stage: dict[str, Any]) -> tuple[float, float, list[dict[str, Any]]]:
    clips: list[dict[str, Any]] = []
    expected_clip_index = 0
    previous_offset = -1.0
    previous_end = -1.0
    for clip_position, raw_clip in enumerate(
        _require_array(stage.get("clips"), "stage clips")
    ):
        clip = _require_object(raw_clip, f"stage clips[{clip_position}]")
        clip_index = _require_int(
            clip.get("stageClipIndex"), f"stage clips[{clip_position}].stageClipIndex"
        )
        if clip_index != expected_clip_index:
            raise ValueError("stageClipIndex must be contiguous and ordered from zero.")
        expected_clip_index += 1
        _require_string(clip.get("clip"), f"stage clips[{clip_position}].clip")
        _require_int(
            clip.get("sourceSkillId"),
            f"stage clips[{clip_position}].sourceSkillId",
            positive=True,
        )
        offset = _require_number(
            clip.get("timelineOffsetSeconds"),
            f"stage clips[{clip_position}].timelineOffsetSeconds",
            non_negative=True,
        )
        length = _require_number(
            clip.get("lengthSeconds"),
            f"stage clips[{clip_position}].lengthSeconds",
            positive=True,
        )
        if offset <= previous_offset:
            raise ValueError("Stage clip timeline offsets must be strictly ordered.")
        if previous_end >= 0.0 and offset + TIMELINE_EPSILON < previous_end:
            raise ValueError("Sequential stage clips overlap in the source timeline.")
        previous_offset = offset
        previous_end = offset + length
        clips.append(
            {
                "clip": clip["clip"],
                "stageClipIndex": clip_index,
                "sourceSkillId": clip["sourceSkillId"],
                "sourceLine": clip.get("sourceLine"),
                "lengthSeconds": length,
                "timelineOffsetSeconds": offset,
            }
        )
    if not clips:
        raise ValueError("Stage must contain at least one sequential clip.")
    start = clips[0]["timelineOffsetSeconds"]
    end = clips[-1]["timelineOffsetSeconds"] + clips[-1]["lengthSeconds"]
    if end <= start:
        raise ValueError("Stage timeline window is empty.")
    declared_start = _require_number(
        stage.get("timelineOffsetSeconds"),
        "stage timelineOffsetSeconds",
        non_negative=True,
    )
    declared_duration = _require_number(
        stage.get("durationSeconds"), "stage durationSeconds", positive=True
    )
    if abs(declared_start - start) > TIMELINE_EPSILON:
        raise ValueError("Stage timeline offset differs from its first clip.")
    if abs((end - start) - declared_duration) > TIMELINE_EPSILON:
        raise ValueError("Stage duration differs from its sequential clip timeline.")
    return start, end, clips


def _artifact_descriptor(
    stage: dict[str, Any]
) -> tuple[int, Path, str, dict[str, Any]]:
    artifacts = _require_array(stage.get("sourceArtifacts"), "stage sourceArtifacts")
    if len(artifacts) != 1:
        raise ValueError("Each stage must have exactly one source artifact.")
    artifact = _require_object(artifacts[0], "stage sourceArtifacts[0]")
    source_skill_id = _require_int(
        artifact.get("sourceSkillId"), "sourceArtifacts[0].sourceSkillId", positive=True
    )
    imported = _require_object(
        artifact.get("importedDocument"), "sourceArtifacts[0].importedDocument"
    )
    evidence: dict[str, dict[str, Any]] = {}
    for evidence_name in (
        "sourceReceipt",
        "externalModuleClosure",
        "conversionReceipt",
    ):
        raw_descriptor = _require_object(
            artifact.get(evidence_name), f"sourceArtifacts[0].{evidence_name}"
        )
        raw_path = _require_string(
            raw_descriptor.get("path"),
            f"sourceArtifacts[0].{evidence_name}.path",
        )
        evidence_path = _resolve_data_path(
            raw_path,
            f"sourceArtifacts[0].{evidence_name}.path",
            require_file=True,
        )
        evidence_hash = _validate_hash(
            evidence_path,
            raw_descriptor.get("sha256"),
            f"sourceArtifacts[0].{evidence_name}.sha256",
        )
        evidence[evidence_name] = {
            "path": raw_path,
            "sha256": evidence_hash,
        }
    raw_normalized_graph = _require_object(
        artifact.get("normalizedGraph"), "sourceArtifacts[0].normalizedGraph"
    )
    normalized_graph_path = _require_string(
        raw_normalized_graph.get("path"), "normalizedGraph.path"
    )
    normalized_graph_hash = _require_string(
        raw_normalized_graph.get("sha256"), "normalizedGraph.sha256"
    )
    if len(normalized_graph_hash) != 64 or any(
        character not in "0123456789abcdef"
        for character in normalized_graph_hash
    ):
        raise ValueError("normalizedGraph.sha256 is not a lowercase SHA-256.")
    normalized_graph_candidate = Path(normalized_graph_path)
    if normalized_graph_candidate.is_absolute():
        if normalized_graph_candidate.is_file():
            _validate_hash(
                normalized_graph_candidate,
                normalized_graph_hash,
                "normalizedGraph.sha256",
            )
    else:
        normalized_graph_file = _resolve_data_path(
            normalized_graph_path,
            "normalizedGraph.path",
            require_file=True,
        )
        _validate_hash(
            normalized_graph_file,
            normalized_graph_hash,
            "normalizedGraph.sha256",
        )
    evidence["normalizedGraph"] = {
        "path": normalized_graph_path,
        "sha256": normalized_graph_hash,
    }
    generated_source_receipt = artifact.get("generatedSourceReceipt")
    if generated_source_receipt is not None:
        generated_source_receipt = _require_object(
            generated_source_receipt, "sourceArtifacts[0].generatedSourceReceipt"
        )
        generated_receipt_path_value = _require_string(
            generated_source_receipt.get("path"), "generatedSourceReceipt.path"
        )
        generated_receipt_path = _resolve_data_path(
            generated_receipt_path_value,
            "generatedSourceReceipt.path",
            require_file=True,
        )
        generated_receipt_hash = _validate_hash(
            generated_receipt_path,
            generated_source_receipt.get("sha256"),
            "generatedSourceReceipt.sha256",
        )
        evidence["generatedSourceReceipt"] = {
            "path": generated_receipt_path_value,
            "sha256": generated_receipt_hash,
        }
    source_path = _resolve_data_path(
        imported.get("path"), "importedDocument.path", require_file=True
    )
    try:
        source_path.relative_to(IMPORTED_ROOT)
    except ValueError as error:
        raise ValueError("Imported document escaped Effects/Imported.") from error
    source_hash = _validate_hash(
        source_path, imported.get("sha256"), "importedDocument.sha256"
    )
    source_effect_id = _require_string(
        imported.get("effectAssetId"), "importedDocument.effectAssetId"
    )
    descriptor = {
        "sourceSkillId": source_skill_id,
        "artifactOrigin": _require_string(
            artifact.get("artifactOrigin"), "sourceArtifacts[0].artifactOrigin"
        ),
        "sourceReceipt": evidence["sourceReceipt"],
        "normalizedGraph": evidence["normalizedGraph"],
        "externalModuleClosure": evidence["externalModuleClosure"],
        "importedDocument": {
            "path": _require_string(imported.get("path"), "importedDocument.path"),
            "sha256": source_hash,
            "effectAssetId": source_effect_id,
        },
        "conversionReceipt": evidence["conversionReceipt"],
    }
    if "generatedSourceReceipt" in evidence:
        descriptor["generatedSourceReceipt"] = evidence["generatedSourceReceipt"]
    return source_skill_id, source_path, source_effect_id, descriptor


def _first_source_event_by_system(
    source_descriptor: dict[str, Any],
) -> dict[str, str]:
    generated_descriptor = source_descriptor.get("generatedSourceReceipt")
    if not isinstance(generated_descriptor, dict):
        return {}
    generated_path = _resolve_data_path(
        generated_descriptor.get("path"),
        "sourceArtifact.generatedSourceReceipt.path",
        require_file=True,
    )
    generated = _load_json(generated_path, "generated source receipt")
    timeline = _require_object(generated.get("timeline"), "generated timeline")
    first_event_by_system: dict[str, str] = {}
    seen_event_ids: set[str] = set()
    for event_index, raw_event in enumerate(
        _require_array(timeline.get("events"), "generated timeline.events")
    ):
        event = _require_object(raw_event, f"generated timeline.events[{event_index}]")
        event_id = _require_string(
            event.get("eventId"), f"generated timeline.events[{event_index}].eventId"
        )
        if event_id in seen_event_ids:
            raise ValueError("Generated source receipt repeats an eventId.")
        seen_event_ids.add(event_id)
        source_system_id = event.get("sourceSystemId")
        if not isinstance(source_system_id, str) or not source_system_id:
            continue
        if not str(event.get("resolutionStatus", "")).startswith("RESOLVED_"):
            continue
        first_event_by_system.setdefault(source_system_id, event_id)
    return first_event_by_system


def _normalized_source_carrier(
    source_element: dict[str, Any], stage_start: float
) -> dict[str, Any]:
    normalized = copy.deepcopy(source_element)
    for field in (
        "id",
        "displayName",
        "groupId",
        "sourceNode",
        "sourcePresentation",
    ):
        normalized.pop(field, None)
    detail = _require_object(normalized.get("detail"), "normalized source detail")
    timing = _require_object(detail.get("timing"), "normalized source timing")
    source_delay = _require_number(
        timing.get("startDelaySeconds"),
        "normalized source startDelaySeconds",
        non_negative=True,
    )
    local_delay = source_delay - stage_start
    if local_delay < -TIMELINE_EPSILON:
        raise ValueError("Normalized source carrier precedes its stage.")
    timing["startDelaySeconds"] = round(max(0.0, local_delay), 6)
    return normalized


def _normalized_source_carrier_hash(
    source_elements: list[dict[str, Any]], stage_start: float
) -> str:
    return _sha256_json(
        [_normalized_source_carrier(element, stage_start) for element in source_elements]
    )


def _normalized_authored_document_hash(document: dict[str, Any]) -> str:
    normalized = copy.deepcopy(document)
    normalized.pop("effectAssetId", None)
    normalized.pop("displayName", None)
    for raw_element in _require_array(
        normalized.get("elements"), "normalized authored elements"
    ):
        element = _require_object(raw_element, "normalized authored element")
        for field in ("id", "displayName", "groupId", "sourceNode"):
            element.pop(field, None)
    return _sha256_json(normalized)


def _target_contract(
    character_class: str,
    skill_id: int,
    stage_index: int,
    stage_count: int,
) -> tuple[str, Path, Path]:
    class_token, class_directory = CLASS_TOKENS[character_class]
    if stage_count == 1:
        target_effect_id = f"effect.{class_token}.skill.{skill_id}.authored-baseline"
    else:
        target_effect_id = f"effect.{class_token}.skill.{skill_id}.ba{stage_index + 1}"
    target_path = AUTHORED_ROOT / f"{target_effect_id}.effect.json"
    receipt_path = (
        RECEIPT_ROOT
        / class_directory
        / f"{target_effect_id}.approximation-receipt.json"
    )
    return target_effect_id, target_path, receipt_path


def _require_sha256(value: Any, label: str) -> str:
    digest = _require_string(value, label)
    if len(digest) != 64 or any(
        character not in "0123456789abcdef" for character in digest
    ):
        raise ValueError(f"{label} is not a lowercase SHA-256.")
    return digest


def _validate_reviewed_renderer_approval(
    *,
    character_class: str,
    skill_id: int,
    stage_index: int,
    stage_count: int,
    clips: list[dict[str, Any]],
    stage: dict[str, Any],
    source_document_sha256: str,
    stage_carriers: list[tuple[int, dict[str, Any]]],
) -> dict[str, Any] | None:
    raw_approval = stage.get("rendererApproximationApproval")
    if raw_approval is None:
        return None
    identity = (character_class, skill_id, stage_index)
    contract = REVIEWED_RENDERER_APPROXIMATION_STAGE_CONTRACTS.get(identity)
    if contract is None:
        raise ValueError(
            "reviewedRendererApproximation is not allowlisted for this exact stage."
        )
    if stage_count != contract["stageCount"] or len(clips) != 1:
        raise ValueError("Reviewed renderer stage cardinality drifted.")
    if clips[0]["clip"] != contract["clip"]:
        raise ValueError("Reviewed renderer source clip drifted.")

    approval = _require_object(raw_approval, "rendererApproximationApproval")
    if approval.get("decision") != "reviewedRendererApproximation":
        raise ValueError("Renderer approval decision is invalid.")
    if approval.get("sourceKind") != contract["sourceKind"]:
        raise ValueError("Renderer approval sourceKind drifted.")
    if approval.get("targetKind") != contract["targetKind"]:
        raise ValueError("Renderer approval targetKind drifted.")
    rationale = _require_string(
        approval.get("rationale"), "rendererApproximationApproval.rationale"
    )
    declared_document_hash = _require_sha256(
        approval.get("sourceDocumentSha256"),
        "rendererApproximationApproval.sourceDocumentSha256",
    )
    if declared_document_hash != source_document_sha256:
        raise ValueError("Reviewed renderer source document hash drifted.")

    source_element_ids = [
        _require_string(value, "rendererApproximationApproval.sourceElementIds[]")
        for value in _require_array(
            approval.get("sourceElementIds"),
            "rendererApproximationApproval.sourceElementIds",
        )
    ]
    if (
        len(source_element_ids) != contract["sourceElementCount"]
        or len(source_element_ids) != len(set(source_element_ids))
        or set(source_element_ids) != set(contract["sourceElementIds"])
    ):
        raise ValueError("Reviewed renderer approval must pin the exact six Elements.")
    source_hashes = _require_object(
        approval.get("sourceElementSha256"),
        "rendererApproximationApproval.sourceElementSha256",
    )
    if set(source_hashes) != set(source_element_ids):
        raise ValueError("Reviewed renderer Element hash keys differ from its ID set.")
    required_reason_codes = [
        _require_string(value, "rendererApproximationApproval.requiredReasonCodes[]")
        for value in _require_array(
            approval.get("requiredReasonCodes"),
            "rendererApproximationApproval.requiredReasonCodes",
        )
    ]
    if not required_reason_codes or required_reason_codes != sorted(
        set(required_reason_codes)
    ) or tuple(required_reason_codes) != contract["requiredReasonCodes"]:
        raise ValueError(
            "Reviewed renderer requiredReasonCodes must be non-empty, unique, and sorted."
        )
    blocker_codes = {
        blocker.get("code")
        for blocker in _require_array(stage.get("blockers"), "stage blockers")
        if isinstance(blocker, dict)
    }
    if "IMPORTED_SOURCE_RECIPE_RUNTIME_PENDING" not in blocker_codes:
        raise ValueError(
            "Reviewed renderer stage lacks SOURCE_RECIPE_RUNTIME_PENDING evidence."
        )

    carriers_by_id: dict[str, dict[str, Any]] = {}
    carrier_ids_in_source_order: list[str] = []
    for _, source_element in stage_carriers:
        element_id = _require_string(source_element.get("id"), "source element ID")
        if element_id in carriers_by_id:
            raise ValueError("Reviewed renderer stage has duplicate source Element IDs.")
        carriers_by_id[element_id] = source_element
        carrier_ids_in_source_order.append(element_id)
    if set(carriers_by_id) != set(source_element_ids):
        raise ValueError(
            "Reviewed renderer approval does not exactly cover the stage visual carriers."
        )
    canonical_hashes: dict[str, str] = {}
    for element_id in carrier_ids_in_source_order:
        source_element = carriers_by_id[element_id]
        analysis = strict_materializer.analyze_source_element(source_element)
        if (
            analysis["sourceKind"] != contract["sourceKind"]
            or analysis["conversionEligibility"] != strict_materializer.UNKNOWN
            or analysis["reasonCodes"] != required_reason_codes
        ):
            raise ValueError(
                "Reviewed renderer source kind/UNKNOWN reason evidence drifted."
            )
        actual_hash = strict_materializer.source_element_sha256(source_element)
        declared_hash = _require_sha256(
            source_hashes[element_id],
            f"rendererApproximationApproval.sourceElementSha256[{element_id}]",
        )
        if declared_hash != actual_hash:
            raise ValueError("Reviewed renderer source Element hash drifted.")
        canonical_hashes[element_id] = actual_hash

    return {
        "decision": "reviewedRendererApproximation",
        # Selection order comes from the immutable source document, never the
        # author-entered approval array order.
        "sourceElementIds": carrier_ids_in_source_order,
        "sourceElementSha256": canonical_hashes,
        "sourceDocumentSha256": declared_document_hash,
        "sourceKind": contract["sourceKind"],
        "targetKind": contract["targetKind"],
        "requiredReasonCodes": required_reason_codes,
        "rationale": rationale,
    }


def _intake_blocker_dispositions(stage: dict[str, Any]) -> list[dict[str, Any]]:
    stage_status = _require_string(stage.get("status"), "stage status")
    raw_blockers = _require_array(stage.get("blockers"), "stage blockers")
    if stage_status == "READY":
        if raw_blockers:
            raise ValueError("READY source intake stage unexpectedly has blockers.")
        return []
    if stage_status != "AVAILABLE_WITH_BLOCKERS":
        raise ValueError(f"Source intake stage is not consumable: {stage_status}")
    if not raw_blockers:
        raise ValueError("AVAILABLE_WITH_BLOCKERS stage has no blocker evidence.")
    dispositions: list[dict[str, Any]] = []
    seen_codes: set[str] = set()
    for index, raw_blocker in enumerate(raw_blockers):
        blocker = _require_object(raw_blocker, f"stage blockers[{index}]")
        code = _require_string(blocker.get("code"), f"stage blockers[{index}].code")
        if code in seen_codes:
            raise ValueError(f"Source intake blocker code is duplicated: {code}")
        seen_codes.add(code)
        count = _require_int(
            blocker.get("count"), f"stage blockers[{index}].count", positive=True
        )
        dispositions.append(
            {
                "sourceBlocker": copy.deepcopy(blocker),
                "sourceBlockerCode": code,
                "sourceBlockerCount": count,
                "disposition": "acceptedApproximation",
                "rationale": (
                    "The pragmatic standalone lane preserves this intake fidelity "
                    "blocker as evidence. Each selected carrier still requires "
                    "resolved executable resources and an explicit per-element "
                    "material/module decision; unresolved candidates remain rejected."
                ),
            }
        )
    return dispositions


def _select_occurrence(
    occurrence_rows: list[tuple[int, dict[str, Any]]],
    *,
    stage_start: float,
    occurrence_index: int,
    target_effect_id: str,
    source_effect_id: str,
    group_texture_bindings: dict[str, list[dict[str, Any]]],
    reviewed_renderer_approval: dict[str, Any] | None = None,
    occurrence_event_ids: dict[str, str] | None = None,
) -> tuple[
    list[dict[str, Any]],
    dict[str, Any],
    set[str],
    list[dict[str, Any]],
]:
    if occurrence_event_ids is None:
        occurrence_event_ids = {}
    candidates: list[dict[str, Any]] = []
    sources_by_id: dict[str, dict[str, Any]] = {}
    kinds_by_id: dict[str, str] = {}
    for source_order, source_element in occurrence_rows:
        source_element_id = _require_string(
            source_element.get("id"), "source element ID"
        )
        try:
            candidate, renderer_kind = _candidate_record(
                source_element,
                source_order,
                group_texture_bindings,
                reviewed_renderer_approval,
                occurrence_event_ids.get(source_element_id, ""),
            )
            candidates.append(candidate)
            sources_by_id[source_element_id] = source_element
            kinds_by_id[source_element_id] = renderer_kind
        except ValueError as error:
            analysis = strict_materializer.analyze_source_element(source_element)
            candidates.append(
                {
                    "sourceElementId": source_element_id,
                    "sourceOrder": source_order,
                    "sourceDocumentKind": analysis["sourceDocumentKind"],
                    "sourceKind": analysis["sourceKind"],
                    "rendererShape": analysis["rendererShape"],
                    "conversionEligibility": analysis["conversionEligibility"],
                    "reasonCodes": copy.deepcopy(analysis["reasonCodes"]),
                    "sourceElementSha256": strict_materializer.source_element_sha256(
                        source_element
                    ),
                    "selectionDecision": "rejected",
                    "rejectionReason": str(error),
                }
            )

    valid_candidates = [
        candidate
        for candidate in candidates
        if candidate.get("selectionDecision") == "candidate"
    ]
    mesh_candidates = sorted(
        [candidate for candidate in valid_candidates if kinds_by_id[candidate["sourceElementId"]] == "mesh"],
        key=_score_sort_key,
    )
    sprite_candidates = sorted(
        [candidate for candidate in valid_candidates if kinds_by_id[candidate["sourceElementId"]] == "sprite"],
        key=_score_sort_key,
    )
    selected_mesh = mesh_candidates[:MAX_MESH_PER_OCCURRENCE]
    selected_sprite = sprite_candidates[:MAX_SPRITE_PER_OCCURRENCE]
    selected = selected_mesh + selected_sprite
    if not selected:
        return [], {
            "occurrenceIndex": occurrence_index,
            "candidates": candidates,
            "selectedSourceElementIds": [],
            "status": "blocked",
            "blocker": "No resolved Mesh or Sprite carrier survived fail-closed validation.",
        }, set(), []

    selected_ids = {candidate["sourceElementId"] for candidate in selected}
    for candidate in candidates:
        if candidate.get("selectionDecision") != "candidate":
            continue
        candidate["selectionDecision"] = (
            "selected" if candidate["sourceElementId"] in selected_ids else "budgetExcluded"
        )
    output_elements: list[dict[str, Any]] = []
    selected_source_elements: list[dict[str, Any]] = []
    for renderer_kind, selected_rows in (
        ("mesh", selected_mesh),
        ("sprite", selected_sprite),
    ):
        for renderer_rank, candidate in enumerate(selected_rows):
            output_element = _copy_selected_element(
                sources_by_id[candidate["sourceElementId"]],
                candidate,
                target_effect_id=target_effect_id,
                source_effect_id=source_effect_id,
                stage_start=stage_start,
                occurrence_index=occurrence_index,
                renderer_kind=renderer_kind,
                renderer_rank=renderer_rank,
            )
            candidate["targetElementId"] = output_element["id"]
            output_elements.append(output_element)
            selected_source_elements.append(
                sources_by_id[candidate["sourceElementId"]]
            )

    first_source = occurrence_rows[0][1]
    first_delay = _source_delay(
        first_source, _require_string(first_source.get("id"), "source element ID")
    )
    occurrence_receipt = {
        "occurrenceIndex": occurrence_index,
        "occurrenceKey": _occurrence_key(first_source, first_delay),
        "sourceEventId": occurrence_event_ids.get(
            _require_string(first_source.get("id"), "source element ID"),
            _source_event_id(first_source),
        ),
        "sourceEventIds": [
            occurrence_event_ids.get(
                _require_string(source_element.get("id"), "source element ID"),
                _source_event_id(source_element),
            )
            for _, source_element in occurrence_rows
            if occurrence_event_ids.get(
                _require_string(source_element.get("id"), "source element ID"),
                _source_event_id(source_element),
            )
        ],
        "sourceTimelineSeconds": first_delay,
        "stageLocalTimeSeconds": max(0.0, first_delay - stage_start),
        "selectionRule": SELECTION_RULE,
        "meshBudget": MAX_MESH_PER_OCCURRENCE,
        "spriteBudget": MAX_SPRITE_PER_OCCURRENCE,
        "candidates": candidates,
        "selectedSourceElementIds": [
            candidate["sourceElementId"] for candidate in selected
        ],
        "status": "selected",
    }
    effective_first_event_id = occurrence_receipt["sourceEventId"]
    if effective_first_event_id:
        occurrence_receipt["occurrenceKey"] = f"event:{effective_first_event_id}"
    if reviewed_renderer_approval is not None:
        occurrence_receipt["occurrenceKey"] = (
            f"reviewed-renderer:{first_delay:.6f}"
        )
        occurrence_receipt["sourceEventId"] = ""
    return output_elements, occurrence_receipt, selected_ids, selected_source_elements


def build_stage_approximation(
    *,
    character_class: str,
    skill_id: int,
    stage: dict[str, Any],
    stage_count: int,
    claimed_source_elements: set[tuple[str, str]],
) -> tuple[Path, dict[str, Any], Path, dict[str, Any]]:
    stage_index = _require_int(stage.get("stageIndex"), "stageIndex")
    if stage_index < 0 or stage_index >= stage_count:
        raise ValueError("stageIndex is outside the skill stage range.")
    stage_id = _require_string(stage.get("stageId"), "stageId")
    expected_stage_id = f"skill.{skill_id}.stage.{stage_index}"
    if stage_id != expected_stage_id:
        raise ValueError(
            f"stageId drifted: expected={expected_stage_id} actual={stage_id}"
        )
    stage_status = _require_string(stage.get("status"), "stage status")
    if stage_status not in CONSUMABLE_INTAKE_STATUSES:
        raise ValueError(f"Source intake stage is not consumable: {stage_status}")
    blocker_dispositions = _intake_blocker_dispositions(stage)
    stage_start, stage_end, clips = _stage_timeline(stage)
    source_skill_id, source_path, source_effect_id, source_descriptor = (
        _artifact_descriptor(stage)
    )
    clip_source_ids = {clip["sourceSkillId"] for clip in clips}
    if clip_source_ids != {source_skill_id}:
        raise ValueError("Stage clips and source artifact do not share one sourceSkillId.")
    stage_source_ids = [
        _require_int(value, "stage sourceSkillIds[]", positive=True)
        for value in _require_array(stage.get("sourceSkillIds"), "stage sourceSkillIds")
    ]
    if stage_source_ids != [source_skill_id]:
        raise ValueError("Stage must own exactly one ordered sourceSkillId.")
    source = _load_json(source_path, "Imported source Effect")
    source_elements = _validate_source_document(source, source_effect_id)
    group_texture_bindings = _source_group_texture_bindings(
        source_elements,
        source_document_sha256=source_descriptor["importedDocument"]["sha256"],
        source_effect_asset_id=source_effect_id,
    )
    first_event_by_system = _first_source_event_by_system(source_descriptor)

    event_ids: list[str] = []
    for raw_event_id in _require_array(stage.get("sourceEventIds"), "sourceEventIds"):
        event_id = _require_string(raw_event_id, "sourceEventIds[]")
        if event_id in event_ids:
            raise ValueError("sourceEventIds must be unique and ordered.")
        event_ids.append(event_id)
    event_id_set = set(event_ids)

    stage_carriers: list[tuple[int, dict[str, Any]]] = []
    occurrence_event_ids: dict[str, str] = {}
    for source_order, element in enumerate(source_elements):
        analysis = strict_materializer.analyze_source_element(element)
        if analysis["sourceKind"] not in {
            "standaloneMesh",
            "meshParticle",
            "standaloneSprite",
            "spriteParticle",
        }:
            continue
        element_id = _require_string(element.get("id"), "source element ID")
        delay = _source_delay(element, element_id)
        if delay + TIMELINE_EPSILON < stage_start or delay >= stage_end - TIMELINE_EPSILON:
            continue
        source_event_id = _source_event_id(element)
        effective_event_id = source_event_id
        if not effective_event_id:
            effective_event_id = first_event_by_system.get(
                _source_system_id(element), ""
            )
        if effective_event_id and event_id_set and effective_event_id not in event_id_set:
            continue
        if effective_event_id:
            occurrence_event_ids[element_id] = effective_event_id
        stage_carriers.append((source_order, element))
    if not stage_carriers:
        raise StageBlocked("Stage has no source Mesh/Sprite occurrence in its timeline.")

    reviewed_renderer_approval = _validate_reviewed_renderer_approval(
        character_class=character_class,
        skill_id=skill_id,
        stage_index=stage_index,
        stage_count=stage_count,
        clips=clips,
        stage=stage,
        source_document_sha256=source_descriptor["importedDocument"]["sha256"],
        stage_carriers=stage_carriers,
    )
    occurrence_map: dict[str, list[tuple[int, dict[str, Any]]]] = {}
    if reviewed_renderer_approval is not None:
        # The reviewed ribbon rows are six UE3 samples of one simultaneous
        # renderer event.  Treat them as one bounded approximation seed so the
        # stage emits only the deterministic top one-to-three Sprites.
        occurrence_map["reviewed-renderer-stage"] = stage_carriers
    else:
        for source_order, element in stage_carriers:
            delay = _source_delay(
                element, _require_string(element.get("id"), "source element ID")
            )
            element_id = _require_string(element.get("id"), "source element ID")
            effective_event_id = occurrence_event_ids.get(element_id, "")
            occurrence_key = (
                f"event:{effective_event_id}"
                if effective_event_id
                else _occurrence_key(element, delay)
            )
            occurrence_map.setdefault(occurrence_key, []).append(
                (source_order, element)
            )

    target_effect_id, target_path, receipt_path = _target_contract(
        character_class, skill_id, stage_index, stage_count
    )
    output_elements: list[dict[str, Any]] = []
    occurrence_receipts: list[dict[str, Any]] = []
    selected_source_elements: list[dict[str, Any]] = []
    newly_claimed: set[tuple[str, str]] = set()
    event_order = {event_id: index for index, event_id in enumerate(event_ids)}
    ordered_occurrences = sorted(
        occurrence_map.values(),
        key=lambda rows: (
            _source_delay(
                rows[0][1],
                _require_string(rows[0][1].get("id"), "source element ID"),
            ),
            event_order.get(
                occurrence_event_ids.get(
                    _require_string(rows[0][1].get("id"), "source element ID"),
                    "",
                ),
                len(event_order),
            ),
            rows[0][0],
        ),
    )
    for occurrence_index, occurrence_rows in enumerate(ordered_occurrences):
        (
            selected_elements,
            receipt,
            selected_ids,
            selected_sources,
        ) = _select_occurrence(
            occurrence_rows,
            stage_start=stage_start,
            occurrence_index=occurrence_index,
            target_effect_id=target_effect_id,
            source_effect_id=source_effect_id,
            group_texture_bindings=group_texture_bindings,
            reviewed_renderer_approval=reviewed_renderer_approval,
            occurrence_event_ids=occurrence_event_ids,
        )
        for source_element_id in selected_ids:
            claim = (_data_relative(source_path), source_element_id)
            if claim in claimed_source_elements or claim in newly_claimed:
                raise ValueError(
                    "A source Element is reused across stages without explicit "
                    f"provenance: {claim}"
                )
            newly_claimed.add(claim)
        output_elements.extend(selected_elements)
        selected_source_elements.extend(selected_sources)
        occurrence_receipts.append(receipt)
    if not output_elements:
        raise StageBlocked(
            "Stage is empty after UNKNOWN/material/resource candidates were rejected."
        )
    claimed_source_elements.update(newly_claimed)

    document = {
        "schema": "lostark.effect-authoring",
        "version": 12,
        "effectAssetId": target_effect_id,
        "displayName": target_effect_id,
        "particleSystem": copy.deepcopy(source["particleSystem"]),
        "modelCues": [],
        "elements": output_elements,
    }
    receipt = {
        "schema": RECEIPT_SCHEMA,
        "version": RECEIPT_VERSION,
        "targetEffectAssetId": target_effect_id,
        "targetAuthoringPath": _data_relative(target_path),
        "characterClass": character_class,
        "productSkillId": skill_id,
        "stageIndex": stage_index,
        "stageId": stage_id,
        "sourceArtifact": source_descriptor,
        "sourceEventIds": event_ids,
        "sourceIntake": {
            "status": stage_status,
            "blockerDispositions": blocker_dispositions,
        },
        "sourceTimeline": {
            "startSeconds": stage_start,
            "endSeconds": stage_end,
            "clips": clips,
        },
        "sourceCarrierEquivalence": {
            "normalizationRule": (
                "drop-id-displayName-groupId-sourceNode-sourcePresentation;"
                "stage-local-startDelay.v1"
            ),
            "elementCount": len(selected_source_elements),
            "normalizedContentSha256": _normalized_source_carrier_hash(
                selected_source_elements, stage_start
            ),
        },
        "consumerContract": {
            "outerCueRoot": "Player",
            "outerCueFollow": True,
            "innerSnapshotRoot": "root",
            "innerSnapshotFollow": False,
        },
        "selectionPolicy": {
            "rule": SELECTION_RULE,
            "meshFirst": True,
            "maxMeshPerOccurrence": MAX_MESH_PER_OCCURRENCE,
            "maxSpritePerOccurrence": MAX_SPRITE_PER_OCCURRENCE,
            "spriteBillboardRollDegrees": SPRITE_BILLBOARD_ROLL_DEGREES,
            "particleOutputAllowed": False,
            "genericPlaceholderAllowed": False,
            "crossSkillBorrowingAllowed": False,
        },
        "occurrences": occurrence_receipts,
        "output": {
            "elementCount": len(output_elements),
            "meshCount": sum(element["kind"] == "mesh" for element in output_elements),
            "spriteCount": sum(
                element["kind"] == "sprite" for element in output_elements
            ),
            "particleCount": 0,
            "documentSha256": _sha256_json(document),
        },
    }
    if reviewed_renderer_approval is not None:
        receipt["rendererApproximationApproval"] = copy.deepcopy(
            reviewed_renderer_approval
        )
    validate_materialized_stage(document, receipt)
    return target_path, document, receipt_path, receipt


def _sha256_json(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()


def _validate_receipt_renderer_approval(
    receipt: dict[str, Any], blocker_dispositions: list[Any]
) -> dict[str, Any] | None:
    raw_approval = receipt.get("rendererApproximationApproval")
    if raw_approval is None:
        return None
    identity = (
        receipt.get("characterClass"),
        receipt.get("productSkillId"),
        receipt.get("stageIndex"),
    )
    contract = REVIEWED_RENDERER_APPROXIMATION_STAGE_CONTRACTS.get(identity)
    if contract is None:
        raise ValueError("Receipt renderer approximation is not exact-stage allowlisted.")
    approval = _require_object(raw_approval, "rendererApproximationApproval")
    if (
        approval.get("decision") != "reviewedRendererApproximation"
        or approval.get("sourceKind") != contract["sourceKind"]
        or approval.get("targetKind") != contract["targetKind"]
    ):
        raise ValueError("Receipt renderer approximation contract drifted.")
    _require_string(approval.get("rationale"), "renderer approval rationale")
    source_ids = [
        _require_string(value, "renderer approval sourceElementIds[]")
        for value in _require_array(
            approval.get("sourceElementIds"), "renderer approval sourceElementIds"
        )
    ]
    if (
        len(source_ids) != contract["sourceElementCount"]
        or len(source_ids) != len(set(source_ids))
        or set(source_ids) != set(contract["sourceElementIds"])
    ):
        raise ValueError("Receipt renderer approval does not pin the exact six Elements.")
    source_hashes = _require_object(
        approval.get("sourceElementSha256"), "renderer approval sourceElementSha256"
    )
    if set(source_hashes) != set(source_ids):
        raise ValueError("Receipt renderer approval hash keys drifted.")
    for element_id in source_ids:
        _require_sha256(
            source_hashes[element_id],
            f"renderer approval sourceElementSha256[{element_id}]",
        )
    required_reasons = [
        _require_string(value, "renderer approval requiredReasonCodes[]")
        for value in _require_array(
            approval.get("requiredReasonCodes"),
            "renderer approval requiredReasonCodes",
        )
    ]
    if (
        not required_reasons
        or required_reasons != sorted(set(required_reasons))
        or tuple(required_reasons) != contract["requiredReasonCodes"]
    ):
        raise ValueError("Receipt renderer approval reason codes drifted.")
    source_artifact = _require_object(receipt.get("sourceArtifact"), "sourceArtifact")
    imported_document = _require_object(
        source_artifact.get("importedDocument"), "sourceArtifact.importedDocument"
    )
    if _require_sha256(
        approval.get("sourceDocumentSha256"),
        "renderer approval sourceDocumentSha256",
    ) != _require_sha256(
        imported_document.get("sha256"), "sourceArtifact.importedDocument.sha256"
    ):
        raise ValueError("Receipt renderer approval source document hash drifted.")
    blocker_codes = {
        row.get("sourceBlockerCode")
        for row in blocker_dispositions
        if isinstance(row, dict)
    }
    if "IMPORTED_SOURCE_RECIPE_RUNTIME_PENDING" not in blocker_codes:
        raise ValueError("Receipt renderer approval lost recipe-runtime blocker evidence.")
    clips = _require_array(
        _require_object(receipt.get("sourceTimeline"), "sourceTimeline").get("clips"),
        "sourceTimeline.clips",
    )
    if (
        len(clips) != 1
        or not isinstance(clips[0], dict)
        or clips[0].get("clip") != contract["clip"]
    ):
        raise ValueError("Receipt renderer approval source clip drifted.")
    return approval


def _validate_distribution_receipt_evidence(
    raw_rows: Any, label: str
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for index, raw_row in enumerate(_require_array(raw_rows, label)):
        row = _require_object(raw_row, f"{label}[{index}]")
        _require_string(row.get("sourceModuleStableId"), f"{label} stableId")
        _require_string(row.get("sourceModuleClassName"), f"{label} className")
        _require_string(row.get("propertyPath"), f"{label} propertyPath")
        _require_sha256(
            row.get("sourceDistributionSha256"), f"{label} distribution SHA-256"
        )
        _require_array(row.get("defaultMinimum"), f"{label} defaultMinimum")
        _require_array(row.get("defaultMaximum"), f"{label} defaultMaximum")
        _require_int(row.get("operation"), f"{label} operation")
        rows.append(row)
    return rows


def _validate_standalone_drawable_resource_decision(
    candidate: dict[str, Any],
    target_element: dict[str, Any],
    *,
    group_texture_bindings: dict[str, list[dict[str, Any]]],
    source_elements_by_id: dict[str, dict[str, Any]],
) -> None:
    decision = _require_object(
        candidate.get("standaloneDrawableResourceDecision"),
        "standaloneDrawableResourceDecision",
    )
    source_resources = [
        _require_object(row, "source drawable resource")
        for row in _require_array(candidate.get("resources"), "source drawable resources")
    ]
    source_element_id = _require_string(
        candidate.get("sourceElementId"), "drawable candidate sourceElementId"
    )
    source_element = source_elements_by_id.get(source_element_id)
    if source_element is None:
        raise ValueError("Drawable candidate is absent from its pinned source document.")
    if candidate.get("sourceElementSha256") != strict_materializer.source_element_sha256(
        source_element
    ):
        raise ValueError("Drawable candidate source Element hash drifted.")
    source_kind = _require_string(
        candidate.get("sourceKind"), "drawable candidate sourceKind"
    )
    expected_source_resources = _validate_element_resources(
        source_element, source_kind, source_element_id
    )
    if source_resources != expected_source_resources:
        raise ValueError("Drawable candidate resources drifted from its source Element.")
    if decision.get("sourceResourceBindingsSha256") != (
        strict_materializer.source_element_sha256(source_resources)
    ):
        raise ValueError("Drawable source resource binding hash drifted.")
    source_evidence = _require_array(
        decision.get("sourceResourceBindings"), "drawable source resource evidence"
    )
    if len(source_evidence) != len(source_resources):
        raise ValueError("Drawable source resource evidence cardinality drifted.")
    source_asset_ids: set[str] = set()
    for index, raw_evidence in enumerate(source_evidence):
        evidence = _require_object(raw_evidence, "drawable source resource evidence")
        source = source_resources[index]
        if (
            evidence.get("sourceOrder") != index
            or evidence.get("slotId") != source.get("slotId")
            or evidence.get("assetId") != source.get("assetId")
            or evidence.get("sourceElementId") != source_element_id
        ):
            raise ValueError("Drawable source resource evidence drifted.")
        asset_id = _validate_resource_asset_id(
            evidence.get("assetId"), "drawable source evidence assetId"
        )
        source_asset_ids.add(asset_id)
        if _require_sha256(
            evidence.get("resourceSha256"), "drawable source resource SHA-256"
        ) != _sha256_file((RESOURCES_ROOT / asset_id).resolve()):
            raise ValueError("Drawable source resource content hash drifted.")

    decision_name = _require_string(decision.get("decision"), "drawable decision")
    allowed_target_asset_ids = set(source_asset_ids)
    if decision_name in {
        "acceptedElementTextureApproximation",
        "acceptedGroupTextureApproximation",
    }:
        promoted_for_allowlist = _require_object(
            decision.get("promotedSourceResource"), "promotedSourceResource"
        )
        allowed_target_asset_ids.add(
            _validate_resource_asset_id(
                promoted_for_allowlist.get("assetId"),
                "promoted Mesh Base assetId",
            )
        )

    target_resources = [
        _require_object(row, "target drawable resource")
        for row in _require_array(
            decision.get("targetResourceBindings"),
            "target drawable resource bindings",
        )
    ]
    if target_element.get("resources") != target_resources or decision.get(
        "targetResourceBindingsSha256"
    ) != strict_materializer.source_element_sha256(target_resources):
        raise ValueError("Drawable target resource bindings drifted from output.")
    target_slots: set[str] = set()
    for resource in target_resources:
        slot_id = _require_string(resource.get("slotId"), "target drawable slotId")
        if slot_id in target_slots:
            raise ValueError("Drawable target resource slots are duplicated.")
        target_slots.add(slot_id)
        asset_id = _validate_resource_asset_id(
            resource.get("assetId"), f"target drawable resource {slot_id}"
        )
        if asset_id not in allowed_target_asset_ids:
            raise ValueError("Drawable target borrowed a non-source resource.")

    detail = _require_object(target_element.get("detail"), "drawable target detail")
    mesh_detail = _require_object(detail.get("mesh"), "drawable target mesh detail")
    target_use_model = decision.get("targetUseModelMaterial") is True
    if (mesh_detail.get("useModelMaterial") is True) != target_use_model:
        raise ValueError("Drawable model-material decision differs from output.")
    disposition = _require_string(
        decision.get("disposition"), "drawable disposition"
    )
    _require_string(decision.get("rationale"), "drawable decision rationale")
    if not isinstance(decision.get("sourceUseModelMaterial"), bool):
        raise ValueError("Drawable source useModelMaterial evidence is invalid.")
    _require_sha256(
        decision.get("sourceMeshDetailSha256"),
        "drawable source Mesh detail SHA-256",
    )
    if target_element.get("kind") == "mesh":
        if "meshModel" not in target_slots:
            raise ValueError("Standalone Mesh target has no meshModel.")
        model = _require_object(decision.get("modelResource"), "modelResource")
        if model.get("slotId") != "meshModel" or model not in source_evidence:
            raise ValueError("Drawable model resource evidence drifted.")
        source_slots = [resource.get("slotId") for resource in source_resources]
        if "base" in source_slots:
            if (
                decision_name != "meshElementMaterialBasePreserved"
                or disposition != "sourceResourcePreserved"
                or target_use_model
                or target_resources != source_resources
            ):
                raise ValueError("Base-backed Mesh drawable decision drifted.")
        else:
            source_group_id = _require_string(
                source_element.get("groupId"), "no-Base Mesh source groupId"
            )
            group_carriers = group_texture_bindings.get(source_group_id, [])
            own_carriers = [
                row
                for row in group_carriers
                if row.get("sourceElementId") == source_element_id
            ]
            expected_scope = (
                "sourceElement" if own_carriers else "sourceCascadeGroup"
            )
            expected_promoted = own_carriers[0] if own_carriers else (
                group_carriers[0] if group_carriers else None
            )
            if expected_promoted is None:
                raise ValueError(
                    "No-Base Mesh has no executable texture in its pinned source group."
                )
            expected_decision = (
                "acceptedElementTextureApproximation"
                if expected_scope == "sourceElement"
                else "acceptedGroupTextureApproximation"
            )
            promoted = _require_object(
                decision.get("promotedSourceResource"), "promotedSourceResource"
            )
            expected_target = copy.deepcopy(source_resources)
            expected_target.append(
                {"slotId": "base", "assetId": expected_promoted["assetId"]}
            )
            expected_model_info = _model_info_evidence(model)
            model_info = _require_object(
                decision.get("modelInfoEvidence"), "modelInfoEvidence"
            )
            expected_preflight = {
                "result": "executableBaseOverride",
                "rendererPath": "Effect_DocumentRenderer.Mesh.BaseOverride",
                "targetUseModelMaterial": False,
                "baseResource": {
                    "slotId": "base",
                    "assetId": expected_promoted["assetId"],
                },
                "baseResourceSha256": expected_promoted["resourceSha256"],
            }
            if (
                decision_name != expected_decision
                or disposition != "acceptedApproximation"
                or target_use_model
                or decision.get("sourceGroupId") != source_group_id
                or decision.get("carrierScope") != expected_scope
                or decision.get("deterministicSelectionPriority")
                != list(MESH_TEXTURE_SELECTION_PRIORITY)
                or promoted != expected_promoted
                or target_resources != expected_target
                or "base" not in target_slots
                or model_info != expected_model_info
                or decision.get("runtimeDrawablePreflight") != expected_preflight
            ):
                raise ValueError("No-Base Mesh texture approximation drifted.")
    elif target_element.get("kind") == "sprite":
        if "meshModel" in target_slots or target_use_model:
            raise ValueError("Standalone Sprite target has an invalid Mesh binding.")
        source_slots = [resource.get("slotId") for resource in source_resources]
        if "base" in source_slots:
            base = _require_object(decision.get("baseResource"), "baseResource")
            if (
                decision_name != "spriteBaseResourcePreserved"
                or disposition != "sourceResourcePreserved"
                or base.get("slotId") != "base"
                or base not in source_evidence
                or target_resources != source_resources
            ):
                raise ValueError("Sprite Base resource preservation drifted.")
        elif decision_name == "sourceMaterialDrawableContractPreserved":
            material = _require_object(
                target_element.get("material"), "source-owned Sprite material"
            )
            source_profile = _require_object(
                material.get("sourceProfile"), "source-owned Sprite profile"
            )
            if (
                candidate.get("materialDecision") != "sourceMaterialPreserved"
                or disposition != "sourceResourcePreserved"
                or target_resources != source_resources
                or source_profile.get("enabled") is not True
                or material.get("templateId") != "effect.source_material"
            ):
                raise ValueError("Source Material-owned Sprite contract drifted.")
        else:
            promoted = _require_object(
                decision.get("promotedSourceResource"), "promotedSourceResource"
            )
            expected_promoted = next(
                (
                    row
                    for row in source_evidence
                    if row.get("slotId") in {"noise", "mask", "emissive", "dissolve"}
                ),
                None,
            )
            expected_target = copy.deepcopy(source_resources)
            if expected_promoted is not None:
                expected_target.append(
                    {"slotId": "base", "assetId": expected_promoted["assetId"]}
                )
            if (
                decision_name != "acceptedSourceTextureBaseAlias"
                or disposition != "acceptedApproximation"
                or promoted != expected_promoted
                or target_resources != expected_target
                or "base" not in target_slots
            ):
                raise ValueError("Sprite source texture Base alias drifted.")
    else:
        raise ValueError("Drawable resource decision target kind is unsupported.")


def _validate_standalone_decisions(
    candidate: dict[str, Any],
    target_element: dict[str, Any],
    *,
    stage_start: float,
    group_texture_bindings: dict[str, list[dict[str, Any]]],
    source_elements_by_id: dict[str, dict[str, Any]],
) -> None:
    _validate_standalone_drawable_resource_decision(
        candidate,
        target_element,
        group_texture_bindings=group_texture_bindings,
        source_elements_by_id=source_elements_by_id,
    )
    source_document_kind = _require_string(
        candidate.get("sourceDocumentKind"), "decision sourceDocumentKind"
    )
    detail = _require_object(target_element.get("detail"), "decision target detail")
    timing = _require_object(detail.get("timing"), "decision target timing")
    lifetime = _require_object(
        candidate.get("standaloneLifetimeDecision"), "standaloneLifetimeDecision"
    )
    lifetime_decision = _require_string(
        lifetime.get("decision"), "standalone lifetime decision"
    )
    target_lifetime = _require_number(
        lifetime.get("targetLifeTimeSeconds"),
        "standalone targetLifeTimeSeconds",
        positive=True,
    )
    if _require_number(
        timing.get("lifeTimeSeconds"), "target lifeTimeSeconds", positive=True
    ) != target_lifetime:
        raise ValueError("Standalone lifetime decision differs from output timing.")
    source_time = _require_number(
        candidate.get("sourceTimeSeconds"),
        "standalone source timeline seconds",
        non_negative=True,
    )
    target_start_offset = _require_number(
        lifetime.get("targetStartDelayOffsetSeconds"),
        "standalone target start delay offset",
        non_negative=True,
    )
    expected_start = max(0.0, source_time - stage_start) + target_start_offset
    actual_start = _require_number(
        timing.get("startDelaySeconds"),
        "target startDelaySeconds",
        non_negative=True,
    )
    if abs(actual_start - expected_start) > TIMELINE_EPSILON:
        raise ValueError("Standalone start-delay decision differs from output timing.")
    _require_number(
        lifetime.get("sourceElementTimingSeconds"),
        "source Element timing evidence",
        positive=True,
    )
    _require_string(lifetime.get("rationale"), "standalone lifetime rationale")
    if source_document_kind == "particle":
        if lifetime_decision not in {
            "finiteEmissionParticleLifetimeMaximum",
            "continuousEmitterWindowPreserved",
            "sourceParticleDetailLifetimeMaximum",
        }:
            raise ValueError("Particle standalone lifetime decision is unsupported.")
        source_emitter_delay = _require_number(
            lifetime.get("sourceEmitterDelaySeconds"),
            "source emitter delay evidence",
            non_negative=True,
        )
        emitter_duration = _require_number(
            lifetime.get("sourceEmitterDurationSeconds"),
            "source emitter duration evidence",
            non_negative=True,
        )
        emitter_loop_count = _require_int(
            lifetime.get("sourceEmitterLoopCount"), "source emitter loop evidence"
        )
        source_burst_count = _require_int(
            lifetime.get("sourceBurstCount"), "source burst count evidence"
        )
        burst_times = [
            _require_number(
                value,
                f"source burst time[{index}]",
                non_negative=True,
            )
            for index, value in enumerate(
                _require_array(
                    lifetime.get("sourceBurstTimesSeconds"),
                    "source burst time evidence",
                )
            )
        ]
        if len(burst_times) != source_burst_count:
            raise ValueError("Source burst timing evidence cardinality drifted.")
        earliest_burst = min(burst_times) if burst_times else 0.0
        latest_burst = max(burst_times) if burst_times else 0.0
        if (
            lifetime.get("sourceEarliestBurstSeconds") != earliest_burst
            or lifetime.get("sourceLatestBurstSeconds") != latest_burst
        ):
            raise ValueError("Source burst timing extrema drifted.")
        burst_envelope = _require_number(
            lifetime.get("sourceBurstEnvelopeSeconds"),
            "source burst envelope evidence",
            non_negative=True,
        )
        for row in _validate_distribution_receipt_evidence(
            lifetime.get("continuousRateEvidence"), "continuous rate evidence"
        ):
            _require_number(
                row.get("maximumAbsoluteValue"),
                "continuous rate maximum",
                non_negative=True,
            )
        lifetime_evidence = _validate_distribution_receipt_evidence(
            lifetime.get("sourceParticleLifetimeEvidence"),
            "source particle lifetime evidence",
        )
        for row in lifetime_evidence:
            _require_number(
                row.get("maximumPositiveSeconds"),
                "particle lifetime maximum evidence",
                non_negative=True,
            )
        if lifetime_decision == "finiteEmissionParticleLifetimeMaximum":
            if lifetime.get("continuousRateIsZero") is not True or not lifetime_evidence:
                raise ValueError("Finite-emission lifetime lacks zero-rate/module evidence.")
            particle_tail = _require_number(
                lifetime.get("sourceParticleLifetimeMaximumSeconds"),
                "source particle lifetime maximum",
                positive=True,
            )
            expected_envelope = (
                max(0, emitter_loop_count - 1) * emitter_duration
                + latest_burst
                - earliest_burst
                if burst_times
                else 0.0
            )
            if (
                abs(burst_envelope - expected_envelope) > TIMELINE_EPSILON
                or abs(target_start_offset - (source_emitter_delay + earliest_burst))
                > TIMELINE_EPSILON
                or abs(target_lifetime - (particle_tail + expected_envelope))
                > TIMELINE_EPSILON
            ):
                raise ValueError("Finite-emission lifetime maximum was not applied.")
        if lifetime_decision == "sourceParticleDetailLifetimeMaximum":
            _require_sha256(
                lifetime.get("sourceParticleDetailSha256"),
                "source particle detail lifetime SHA-256",
            )
            detail_values = [
                _require_number(
                    value,
                    f"source particle detail lifetime[{index}]",
                    positive=True,
                )
                for index, value in enumerate(
                    _require_array(
                        lifetime.get("sourceParticleDetailLifetimeSeconds"),
                        "source particle detail lifetime",
                    )
                )
            ]
            expected_envelope = (
                max(0, emitter_loop_count - 1) * emitter_duration
                + latest_burst
                - earliest_burst
                if burst_times
                else 0.0
            )
            if (
                len(detail_values) != 2
                or abs(burst_envelope - expected_envelope) > TIMELINE_EPSILON
                or abs(target_start_offset - (source_emitter_delay + earliest_burst))
                > TIMELINE_EPSILON
                or abs(target_lifetime - (max(detail_values) + expected_envelope))
                > TIMELINE_EPSILON
            ):
                raise ValueError("Particle detail lifetime maximum was not applied.")
        if lifetime_decision == "continuousEmitterWindowPreserved" and (
            burst_envelope != 0.0
            or abs(target_start_offset - source_emitter_delay) > TIMELINE_EPSILON
            or target_lifetime != lifetime.get("sourceElementTimingSeconds")
        ):
            raise ValueError("Continuous emitter timing window was not preserved.")
    elif (
        lifetime_decision != "sourceStandaloneTimingPreserved"
        or target_start_offset != 0.0
    ):
        raise ValueError("Native standalone timing decision drifted.")

    size = _require_object(
        candidate.get("standaloneSizeDecision"), "standaloneSizeDecision"
    )
    size_decision = _require_string(size.get("decision"), "standalone size decision")
    target_start_scale = [
        _require_number(value, f"target start scale[{index}]")
        for index, value in enumerate(
            _require_array(size.get("targetStartScale"), "target start scale")
        )
    ]
    target_end_scale = [
        _require_number(value, f"target end scale[{index}]")
        for index, value in enumerate(
            _require_array(size.get("targetEndScale"), "target end scale")
        )
    ]
    if len(target_start_scale) != 3 or len(target_end_scale) != 3:
        raise ValueError("Standalone size decision cardinality drifted.")
    transform = _require_object(detail.get("transform"), "decision target transform")
    linear_lerp = _require_object(detail.get("linearLerp"), "decision target linearLerp")
    if (
        transform.get("scale") != target_start_scale
        or (linear_lerp.get("scale") is True)
        != (size.get("targetLinearLerpScaleEnabled") is True)
        or linear_lerp.get("endScale") != target_end_scale
    ):
        raise ValueError("Standalone size decision differs from output scale.")
    _require_string(size.get("rationale"), "standalone size rationale")
    if source_document_kind == "particle":
        if size_decision != "particleSizeEndpointBake":
            raise ValueError("Particle standalone size was not baked.")
        start_size = [
            _require_number(value, f"source particle startSize[{index}]", non_negative=True)
            for index, value in enumerate(
                _require_array(
                    size.get("sourceParticleStartSize"), "source particle startSize"
                )
            )
        ]
        end_size = [
            _require_number(value, f"source particle endSize[{index}]", non_negative=True)
            for index, value in enumerate(
                _require_array(
                    size.get("sourceParticleEndSize"), "source particle endSize"
                )
            )
        ]
        if len(start_size) != 2 or len(end_size) != 2:
            raise ValueError("Particle size receipt cardinality drifted.")
        _require_sha256(
            size.get("sourceParticleDetailSha256"), "source particle detail SHA-256"
        )
        representative_decision = size.get("representativeDecision")
        if representative_decision == "sourceLookupFirstSampleRepresentative":
            expected_axis = (
                "mesh.raw-xyz-to-client-xzy.centimeters.v1"
                if target_element.get("kind") == "mesh"
                else "sprite.raw-xy-centimeters.preserve-depth.v1"
            )
        elif representative_decision == "runtimeParticleDetailFallbackRepresentative":
            expected_axis = (
                "mesh.imported-detail-xy-average-depth.runtime-fallback.v1"
                if target_element.get("kind") == "mesh"
                else "sprite.imported-detail-xy.runtime-fallback.v1"
            )
        else:
            raise ValueError("Particle size representative rule drifted.")
        if size.get("axisMapping") != expected_axis:
            raise ValueError("Particle-to-standalone size axis mapping drifted.")
        _require_number(
            size.get("minimumPositiveFactor"),
            "minimum positive size factor",
            positive=True,
        )
        mirror = _require_object(
            size.get("signedMirrorDisposition"), "signed mirror disposition"
        )
        if mirror.get("disposition") != "acceptedApproximation":
            raise ValueError("Signed mirror loss was not accepted explicitly.")
        _require_string(mirror.get("rationale"), "signed mirror rationale")
        for evidence_name in (
            "sourceInitialSizeSamples",
            "sourceEvolutionSizeSamples",
        ):
            for raw_sample in _require_array(size.get(evidence_name), evidence_name):
                sample = _require_object(raw_sample, evidence_name)
                _require_string(sample.get("sourceModuleStableId"), "size sample stableId")
                _require_string(sample.get("propertyPath"), "size sample propertyPath")
                _require_sha256(
                    sample.get("sourceDistributionSha256"),
                    "size sample distribution SHA-256",
                )
                raw_vector = _require_array(
                    sample.get("rawSignedVector"), "size sample rawSignedVector"
                )
                if len(raw_vector) != 3:
                    raise ValueError("Size sample vector cardinality drifted.")
                for index, value in enumerate(raw_vector):
                    _require_number(value, f"size sample raw vector[{index}]")
        size_modules = _require_array(
            size.get("sourceSizeModuleEvidence"), "source size module evidence"
        )
        if (
            representative_decision == "sourceLookupFirstSampleRepresentative"
            and not size_modules
        ):
            raise ValueError("Particle size decision lacks module evidence.")
        for raw_module in size_modules:
            module = _require_object(raw_module, "source size module evidence")
            _require_string(module.get("sourceModuleStableId"), "size module stableId")
            _require_string(module.get("sourceModuleClassName"), "size module className")
            _require_sha256(module.get("sourceModuleSha256"), "size module SHA-256")
            _validate_distribution_receipt_evidence(
                module.get("distributions"), "size module distributions"
            )
        evolution = _require_array(
            size.get("sourceSizeEvolutionModuleEvidence"),
            "source size evolution evidence",
        )
        if bool(evolution) and linear_lerp.get("scale") is not True:
            raise ValueError("Size-over-life evidence was not baked as endpoint lerp.")
    elif size_decision != "sourceStandaloneScalePreserved":
        raise ValueError("Native standalone scale decision drifted.")


def validate_materialized_stage(
    document: dict[str, Any], receipt: dict[str, Any]
) -> None:
    if (
        document.get("schema") != "lostark.effect-authoring"
        or document.get("version") != 12
    ):
        raise ValueError("Materialized Effect schema/version is invalid.")
    if (
        receipt.get("schema") != RECEIPT_SCHEMA
        or receipt.get("version") != RECEIPT_VERSION
    ):
        raise ValueError("Approximation receipt schema/version is invalid.")
    target_effect_id = _require_string(
        receipt.get("targetEffectAssetId"), "receipt targetEffectAssetId"
    )
    if document.get("effectAssetId") != target_effect_id:
        raise ValueError("Document and receipt target IDs differ.")
    source_artifact = _require_object(receipt.get("sourceArtifact"), "sourceArtifact")
    imported_document = _require_object(
        source_artifact.get("importedDocument"), "sourceArtifact.importedDocument"
    )
    source_path = _resolve_data_path(
        imported_document.get("path"),
        "sourceArtifact.importedDocument.path",
        require_file=True,
    )
    try:
        source_path.relative_to(IMPORTED_ROOT)
    except ValueError as error:
        raise ValueError("Receipt Imported document escaped Effects/Imported.") from error
    source_document_sha256 = _validate_hash(
        source_path,
        imported_document.get("sha256"),
        "sourceArtifact.importedDocument.sha256",
    )
    source_effect_asset_id = _require_string(
        imported_document.get("effectAssetId"),
        "sourceArtifact.importedDocument.effectAssetId",
    )
    source_document = _load_json(source_path, "receipt Imported source Effect")
    source_elements = _validate_source_document(
        source_document, source_effect_asset_id
    )
    source_elements_by_id = {
        _require_string(element.get("id"), "receipt source Element ID"): element
        for element in source_elements
    }
    group_texture_bindings = _source_group_texture_bindings(
        source_elements,
        source_document_sha256=source_document_sha256,
        source_effect_asset_id=source_effect_asset_id,
    )
    source_intake = _require_object(receipt.get("sourceIntake"), "sourceIntake")
    source_intake_status = _require_string(
        source_intake.get("status"), "sourceIntake.status"
    )
    blocker_dispositions = _require_array(
        source_intake.get("blockerDispositions"),
        "sourceIntake.blockerDispositions",
    )
    if source_intake_status == "READY":
        if blocker_dispositions:
            raise ValueError("READY source intake receipt carries blocker dispositions.")
    elif source_intake_status == "AVAILABLE_WITH_BLOCKERS":
        if not blocker_dispositions:
            raise ValueError("Available source blockers were not dispositioned.")
        blocker_codes: set[str] = set()
        for row in blocker_dispositions:
            row = _require_object(row, "source intake blocker disposition")
            blocker_code = _require_string(
                row.get("sourceBlockerCode"), "source blocker code"
            )
            if blocker_code in blocker_codes:
                raise ValueError("Source intake blocker dispositions are duplicated.")
            blocker_codes.add(blocker_code)
            if row.get("disposition") != "acceptedApproximation":
                raise ValueError("Source intake blocker was not accepted explicitly.")
            _require_string(row.get("rationale"), "source blocker rationale")
            _require_object(row.get("sourceBlocker"), "raw source blocker evidence")
    else:
        raise ValueError("Approximation receipt has an unconsumable intake status.")
    reviewed_renderer_approval = _validate_receipt_renderer_approval(
        receipt, blocker_dispositions
    )
    source_timeline = _require_object(receipt.get("sourceTimeline"), "sourceTimeline")
    stage_start = _require_number(
        source_timeline.get("startSeconds"),
        "sourceTimeline.startSeconds",
        non_negative=True,
    )
    source_equivalence = _require_object(
        receipt.get("sourceCarrierEquivalence"), "sourceCarrierEquivalence"
    )
    if source_equivalence.get("normalizationRule") != (
        "drop-id-displayName-groupId-sourceNode-sourcePresentation;"
        "stage-local-startDelay.v1"
    ):
        raise ValueError("Source carrier equivalence normalization rule drifted.")
    _require_sha256(
        source_equivalence.get("normalizedContentSha256"),
        "sourceCarrierEquivalence.normalizedContentSha256",
    )
    elements = _require_array(document.get("elements"), "materialized elements")
    if not elements:
        raise ValueError("Materialized stage is empty.")
    by_id: dict[str, dict[str, Any]] = {}
    for element in elements:
        element = _require_object(element, "materialized element")
        element_id = _require_string(element.get("id"), "materialized element ID")
        if element_id in by_id:
            raise ValueError("Materialized stage has duplicate Element IDs.")
        by_id[element_id] = element
        if element.get("kind") not in {"mesh", "sprite"}:
            raise ValueError("Approximation output may contain only Mesh/Sprite.")
        target_resources = [
            _require_object(row, "materialized target resource")
            for row in _require_array(
                element.get("resources"), "materialized target resources"
            )
        ]
        target_slots = {
            _require_string(row.get("slotId"), "materialized target resource slotId")
            for row in target_resources
        }
        if len(target_slots) != len(target_resources):
            raise ValueError("Approximation output has duplicate resource slots.")
        target_detail = _require_object(
            element.get("detail"), "materialized drawable detail"
        )
        target_mesh = _require_object(
            target_detail.get("mesh"), "materialized drawable mesh detail"
        )
        target_material = _require_object(
            element.get("material"), "materialized drawable material"
        )
        target_source_profile = _require_object(
            target_material.get("sourceProfile"),
            "materialized drawable source profile",
        )
        source_material_owns_sprite = (
            target_material.get("templateId") == "effect.source_material"
            and target_source_profile.get("enabled") is True
        )
        if element.get("kind") == "mesh" and (
            "meshModel" not in target_slots
            or "base" not in target_slots
            or target_mesh.get("useModelMaterial") is True
        ):
            raise ValueError(
                "Standalone Mesh requires meshModel and an explicit Base override."
            )
        if element.get("kind") == "sprite" and (
            "meshModel" in target_slots
            or ("base" not in target_slots and not source_material_owns_sprite)
        ):
            raise ValueError("Standalone Sprite requires a Base texture binding.")
        recipe = _require_object(
            element.get("sourceRecipe"), "materialized sourceRecipe"
        )
        if recipe.get("enabled") is not False or recipe.get("modules") != []:
            raise ValueError("Approximation output retained an executable source recipe.")
        attachment = _require_object(
            element.get("actionCueAttachment"), "materialized attachment"
        )
        if (
            attachment.get("enabled") is not True
            or attachment.get("runtimeAnchorSlotId") != "root"
            or attachment.get("follow") is not False
        ):
            raise ValueError("Approximation element is not an authored root snapshot.")
        sprite = _require_object(
            _require_object(element.get("detail"), "materialized detail").get("sprite"),
            "materialized sprite detail",
        )
        if element.get("kind") == "sprite" and (
            sprite.get("billboard") is not True
            or _require_number(
                sprite.get("billboardRollDegrees"), "Sprite billboard roll"
            )
            != SPRITE_BILLBOARD_ROLL_DEGREES
        ):
            raise ValueError("Authored Sprite does not carry the per-element -90 roll.")

    selected_source_ids: set[str] = set()
    selected_target_ids: set[str] = set()
    reviewed_candidate_ids: set[str] = set()
    reviewed_selected_count = 0
    for occurrence_index, raw_occurrence in enumerate(
        _require_array(receipt.get("occurrences"), "receipt occurrences")
    ):
        occurrence = _require_object(
            raw_occurrence, f"receipt occurrences[{occurrence_index}]"
        )
        candidates = _require_array(
            occurrence.get("candidates"), "receipt occurrence candidates"
        )
        if reviewed_renderer_approval is not None:
            for raw_candidate in candidates:
                candidate = _require_object(raw_candidate, "receipt candidate")
                source_element_id = _require_string(
                    candidate.get("sourceElementId"), "candidate sourceElementId"
                )
                if source_element_id not in reviewed_renderer_approval[
                    "sourceElementIds"
                ]:
                    raise ValueError(
                        "Reviewed renderer receipt contains an unapproved source Element."
                    )
                if (
                    candidate.get("sourceKind") != "spriteParticle"
                    or candidate.get("conversionEligibility")
                    != strict_materializer.UNKNOWN
                    or candidate.get("reasonCodes")
                    != reviewed_renderer_approval["requiredReasonCodes"]
                    or candidate.get("sourceElementSha256")
                    != reviewed_renderer_approval["sourceElementSha256"][
                        source_element_id
                    ]
                ):
                    raise ValueError(
                        "Reviewed renderer UNKNOWN source evidence was not preserved."
                    )
                reviewed_candidate_ids.add(source_element_id)
                selection_decision = candidate.get("selectionDecision")
                if selection_decision == "rejected":
                    rejection_reason = _require_string(
                        candidate.get("rejectionReason"),
                        "reviewed renderer rejectionReason",
                    ).casefold()
                    if not any(
                        token in rejection_reason
                        for token in ("unresolved", "material", "resource")
                    ):
                        raise ValueError(
                            "Reviewed renderer Element was rejected for a non-resource reason."
                        )
                    continue
                if selection_decision not in {"selected", "budgetExcluded"}:
                    raise ValueError(
                        "Reviewed renderer approved Element failed closed validation."
                    )
        selected_candidates = [
            _require_object(candidate, "receipt candidate")
            for candidate in candidates
            if isinstance(candidate, dict)
            and candidate.get("selectionDecision") == "selected"
        ]
        mesh_count = sum(
            candidate.get("sourceKind") in {"standaloneMesh", "meshParticle"}
            for candidate in selected_candidates
        )
        sprite_count = sum(
            candidate.get("sourceKind") in {"standaloneSprite", "spriteParticle"}
            for candidate in selected_candidates
        )
        if mesh_count > MAX_MESH_PER_OCCURRENCE:
            raise ValueError("Occurrence exceeds the five-Mesh layer budget.")
        if sprite_count > MAX_SPRITE_PER_OCCURRENCE:
            raise ValueError("Occurrence exceeds the three-Sprite layer budget.")
        if not selected_candidates:
            if occurrence.get("status") == "blocked":
                continue
            raise ValueError("Selected occurrence is empty.")
        for candidate in selected_candidates:
            source_element_id = _require_string(
                candidate.get("sourceElementId"), "selected sourceElementId"
            )
            target_element_id = _require_string(
                candidate.get("targetElementId"), "selected targetElementId"
            )
            if (
                source_element_id in selected_source_ids
                or target_element_id in selected_target_ids
            ):
                raise ValueError("Selection receipt reuses a source or target Element.")
            selected_source_ids.add(source_element_id)
            selected_target_ids.add(target_element_id)
            if target_element_id not in by_id:
                raise ValueError("Selection receipt target Element is missing.")
            _validate_standalone_decisions(
                candidate,
                by_id[target_element_id],
                stage_start=stage_start,
                group_texture_bindings=group_texture_bindings,
                source_elements_by_id=source_elements_by_id,
            )
            eligibility = _require_string(
                candidate.get("conversionEligibility"),
                "selected conversionEligibility",
            )
            if eligibility == strict_materializer.UNKNOWN:
                if (
                    reviewed_renderer_approval is None
                    or source_element_id
                    not in reviewed_renderer_approval["sourceElementIds"]
                    or candidate.get("sourceKind") != "spriteParticle"
                    or by_id[target_element_id].get("kind") != "sprite"
                ):
                    raise ValueError("UNKNOWN source was selected without exact approval.")
                reviewed_selected_count += 1
            source_document_kind = _require_string(
                candidate.get("sourceDocumentKind"), "selected sourceDocumentKind"
            )
            conversion_decision = _require_string(
                candidate.get("conversionDecision"), "selected conversionDecision"
            )
            source_module_ids = [
                _require_string(value, "selected sourceModuleStableIds[]")
                for value in _require_array(
                    candidate.get("sourceModuleStableIds"),
                    "selected sourceModuleStableIds",
                )
            ]
            if len(source_module_ids) != len(set(source_module_ids)):
                raise ValueError("Source module stable IDs are duplicated.")
            dispositions = _require_array(
                candidate.get("removedModuleDispositions"),
                "selected removedModuleDispositions",
            )
            if source_document_kind == "particle":
                if eligibility == strict_materializer.PARTICLE_REQUIRED and (
                    conversion_decision != "reviewedStandaloneApproximation"
                ):
                    raise ValueError(
                        "Particle-required carrier lacks reviewedStandaloneApproximation."
                    )
                if eligibility == strict_materializer.UNKNOWN and (
                    conversion_decision != "reviewedRendererApproximation"
                ):
                    raise ValueError(
                        "Approved UNKNOWN carrier lacks reviewedRendererApproximation."
                    )
                if not dispositions:
                    raise ValueError("Particle conversion lacks module dispositions.")
                module_ids: set[str] = set()
                disposition_order: list[str] = []
                for row in dispositions:
                    row = _require_object(row, "removed module disposition")
                    module_id = _require_string(
                        row.get("sourceModuleStableId"), "source module stableId"
                    )
                    if module_id in module_ids:
                        raise ValueError("Removed module dispositions are incomplete/duplicate.")
                    module_ids.add(module_id)
                    disposition_order.append(module_id)
                    if row.get("disposition") != "acceptedApproximation":
                        raise ValueError("Removed module was not accepted as approximation.")
                    _require_string(row.get("rationale"), "approximation rationale")
                if disposition_order != source_module_ids:
                    raise ValueError(
                        "Removed module dispositions do not cover every source module."
                    )
                module_evidence = _require_array(
                    candidate.get("sourceModuleEvidence"),
                    "selected sourceModuleEvidence",
                )
                evidence_ids = [
                    _require_string(
                        _require_object(row, "source module evidence").get(
                            "sourceModuleStableId"
                        ),
                        "source module evidence stableId",
                    )
                    for row in module_evidence
                ]
                if evidence_ids != source_module_ids:
                    raise ValueError("Source module evidence does not cover every module.")
                for evidence_row, disposition_row in zip(
                    module_evidence, dispositions, strict=True
                ):
                    evidence_row = _require_object(
                        evidence_row, "source module evidence"
                    )
                    disposition_row = _require_object(
                        disposition_row, "removed module disposition"
                    )
                    class_name = _require_string(
                        evidence_row.get("sourceModuleClassName"),
                        "source module evidence className",
                    )
                    if disposition_row.get("sourceModuleClassName") != class_name:
                        raise ValueError(
                            "Removed module disposition class evidence drifted."
                        )
                    _require_sha256(
                        evidence_row.get("sourceModuleSha256"),
                        "source module evidence SHA-256",
                    )
                if eligibility == strict_materializer.UNKNOWN:
                    evidence_classes = {
                        _require_string(
                            _require_object(row, "source module evidence").get(
                                "sourceModuleClassName"
                            ),
                            "source module evidence className",
                        ).casefold()
                        for row in module_evidence
                    }
                    if "particlemoduletypedataribbon" not in evidence_classes:
                        raise ValueError(
                            "Reviewed renderer evidence lost ParticleModuleTypeDataRibbon."
                        )
            elif dispositions:
                raise ValueError("Native standalone carrier claims removed source modules.")
            elif source_module_ids:
                raise ValueError("Native standalone carrier claims source module removals.")
            material_decision = _require_string(
                candidate.get("materialDecision"), "selected materialDecision"
            )
            provenance = _require_object(
                candidate.get("materialProvenance"), "selected materialProvenance"
            )
            raw_profile = _require_object(
                provenance.get("sourceProfile"), "raw source material profile"
            )
            raw_runtime_profile_value = raw_profile.get("runtimeShaderProfileId", "")
            raw_runtime_profile = (
                raw_runtime_profile_value
                if isinstance(raw_runtime_profile_value, str)
                else ""
            )
            raw_semantic_status_value = raw_profile.get("semanticStatus", "")
            raw_semantic_status = (
                raw_semantic_status_value
                if isinstance(raw_semantic_status_value, str)
                else ""
            )
            raw_textures_value = raw_profile.get("textures", [])
            raw_textures = (
                raw_textures_value if isinstance(raw_textures_value, list) else []
            )
            requires_standard_material = (
                raw_profile.get("enabled") is not True
                or not raw_runtime_profile
                or raw_runtime_profile == FALLBACK_BLOCKED_RUNTIME_PROFILE
                or raw_semantic_status.casefold()
                in {"", "unresolved", "unsupported", "missing_resource"}
                or any(
                    isinstance(texture, dict)
                    and texture.get("assetId") in (None, "")
                    for texture in raw_textures
                )
            )
            if requires_standard_material and (
                material_decision != "acceptedStandardApproximation"
            ):
                raise ValueError("Fallback material lacks acceptedStandardApproximation.")
            output_material = _require_object(
                by_id[target_element_id].get("material"), "output material"
            )
            if output_material.get("sourceMaterialPath") != provenance.get(
                "sourceMaterialPath"
            ):
                raise ValueError("Raw sourceMaterialPath provenance was not preserved.")
            if material_decision == "acceptedStandardApproximation":
                if (
                    output_material.get("templateId") != "effect.standard"
                    or output_material.get("sourceProfile") != {"enabled": False}
                ):
                    raise ValueError(
                        "Standard approximation exposed an executable source profile."
                    )
            drawable_decision = _require_object(
                candidate.get("standaloneDrawableResourceDecision"),
                "selected drawable resource decision",
            )
            if by_id[target_element_id].get("resources") != (
                drawable_decision.get("targetResourceBindings")
            ):
                raise ValueError("Reviewed drawable target resources were not applied.")
            source_element_hash = _require_string(
                candidate.get("sourceElementSha256"), "sourceElementSha256"
            )
            if len(source_element_hash) != 64 or any(
                character not in "0123456789abcdef"
                for character in source_element_hash
            ):
                raise ValueError("Selected sourceElementSha256 is invalid.")

    if selected_target_ids != set(by_id):
        raise ValueError("Output Element set differs from the selection receipt.")
    if source_equivalence.get("elementCount") != len(selected_target_ids):
        raise ValueError("Source carrier equivalence Element count drifted.")
    if reviewed_renderer_approval is not None:
        if reviewed_candidate_ids != set(
            reviewed_renderer_approval["sourceElementIds"]
        ):
            raise ValueError("Reviewed renderer receipt does not cover all six Elements.")
        if not (1 <= reviewed_selected_count <= MAX_SPRITE_PER_OCCURRENCE):
            raise ValueError("Reviewed renderer must select one-to-three Sprites.")
        if any(element.get("kind") != "sprite" for element in elements):
            raise ValueError("Reviewed renderer approximation emitted a non-Sprite target.")
    output = _require_object(receipt.get("output"), "receipt output")
    if output.get("particleCount") != 0:
        raise ValueError("Approximation receipt claims Particle output.")
    if output.get("documentSha256") != _sha256_json(document):
        raise ValueError("Approximation output hash drifted from its receipt.")


def _validate_protected_target(path: Path, target_effect_id: str) -> None:
    if not path.is_file():
        raise ValueError(f"Protected Authored target is missing: {path}")
    document = _load_json(path, "protected Authored target")
    if document.get("effectAssetId") != target_effect_id:
        raise ValueError("Protected Authored target has the wrong Effect asset ID.")
    elements = _require_array(document.get("elements"), "protected elements")
    if not elements or any(
        not isinstance(element, dict) or element.get("kind") not in {"mesh", "sprite"}
        for element in elements
    ):
        raise ValueError("Protected baseline is not the standalone Mesh/Sprite baseline.")


def _validate_replaceable_legacy_particle_target(
    path: Path, target_effect_id: str
) -> None:
    if target_effect_id not in REPLACEABLE_LEGACY_PARTICLE_TARGETS:
        raise ValueError("Target is not in the reviewed legacy replacement allowlist.")
    document = _load_json(path, "replaceable legacy Particle target")
    if (
        document.get("schema") != "lostark.effect-authoring"
        or document.get("version") != 12
        or document.get("effectAssetId") != target_effect_id
    ):
        raise ValueError("Legacy Particle target identity/schema drifted.")
    elements = _require_array(document.get("elements"), "legacy Particle elements")
    kinds = {
        element.get("kind")
        for element in elements
        if isinstance(element, dict)
    }
    if "particle" not in kinds or kinds & {"mesh", "sprite"}:
        raise ValueError(
            "Legacy replacement target is no longer the Particle-only product document."
        )


def _validate_intentionally_silent_stage(
    *,
    character_class: str,
    skill_id: int,
    stage: dict[str, Any],
    stage_count: int,
) -> dict[str, Any] | None:
    raw_decision = stage.get("completionDecision")
    if raw_decision is None:
        return None
    stage_index = _require_int(stage.get("stageIndex"), "stageIndex")
    identity = (character_class, skill_id, stage_index)
    contract = INTENTIONALLY_SILENT_STAGE_CONTRACTS.get(identity)
    if contract is None:
        raise ValueError("sourceIntentionallySilent is not allowlisted for this exact stage.")
    if stage_count != contract["stageCount"]:
        raise ValueError("Intentionally-silent stage cardinality drifted.")
    expected_stage_id = f"skill.{skill_id}.stage.{stage_index}"
    if stage.get("stageId") != expected_stage_id:
        raise ValueError("Intentionally-silent stageId drifted.")
    blocker_dispositions = _intake_blocker_dispositions(stage)
    stage_start, stage_end, clips = _stage_timeline(stage)
    if len(clips) != 1 or clips[0]["clip"] != contract["clip"]:
        raise ValueError("Intentionally-silent source clip drifted.")
    source_skill_id, source_path, source_effect_id, source_descriptor = (
        _artifact_descriptor(stage)
    )
    if {clip["sourceSkillId"] for clip in clips} != {source_skill_id}:
        raise ValueError("Silent stage clip/source artifact identity drifted.")
    stage_source_ids = [
        _require_int(value, "stage sourceSkillIds[]", positive=True)
        for value in _require_array(stage.get("sourceSkillIds"), "stage sourceSkillIds")
    ]
    if stage_source_ids != [source_skill_id]:
        raise ValueError("Silent stage must own exactly one sourceSkillId.")
    if _require_array(stage.get("sourceEventIds"), "sourceEventIds"):
        raise ValueError("Intentionally-silent stage unexpectedly declares Effect events.")

    decision = _require_object(raw_decision, "completionDecision")
    if decision.get("decision") != "sourceIntentionallySilent":
        raise ValueError("Intentionally-silent completion decision is invalid.")
    rationale = _require_string(decision.get("rationale"), "completionDecision.rationale")
    evidence = _require_object(decision.get("evidence"), "completionDecision.evidence")
    if evidence.get("clip") != contract["clip"]:
        raise ValueError("Intentionally-silent evidence clip drifted.")
    if (
        _require_int(evidence.get("effectNotifyCount"), "effectNotifyCount") != 0
        or _require_int(evidence.get("shakeNotifyCount"), "shakeNotifyCount") != 0
    ):
        raise ValueError("Intentionally-silent evidence contains visual notifies.")
    observed_notify_kinds = [
        _require_string(value, "observedNotifyKinds[]")
        for value in _require_array(
            evidence.get("observedNotifyKinds"), "observedNotifyKinds"
        )
    ]
    if (
        len(observed_notify_kinds) != len(set(observed_notify_kinds))
        or frozenset(observed_notify_kinds) != contract["observedNotifyKinds"]
    ):
        raise ValueError("Intentionally-silent control notify evidence drifted.")

    source = _load_json(source_path, "silent Imported source Effect")
    source_elements = _validate_source_document(source, source_effect_id)
    visual_rows: list[str] = []
    for source_element in source_elements:
        analysis = strict_materializer.analyze_source_element(source_element)
        if analysis["sourceKind"] not in {
            "standaloneMesh",
            "meshParticle",
            "standaloneSprite",
            "spriteParticle",
        }:
            continue
        element_id = _require_string(source_element.get("id"), "source element ID")
        delay = _source_delay(source_element, element_id)
        if stage_start - TIMELINE_EPSILON <= delay < stage_end - TIMELINE_EPSILON:
            visual_rows.append(element_id)
    if visual_rows:
        raise ValueError(
            "Intentionally-silent stage contains source Mesh/Sprite presentation."
        )
    return {
        "decision": "sourceIntentionallySilent",
        "rationale": rationale,
        "evidence": {
            "clip": contract["clip"],
            "effectNotifyCount": 0,
            "shakeNotifyCount": 0,
            "observedNotifyKinds": sorted(contract["observedNotifyKinds"]),
        },
        "sourceArtifact": source_descriptor,
        "sourceIntake": {
            "status": _require_string(stage.get("status"), "stage status"),
            "blockerDispositions": blocker_dispositions,
        },
        "sourceTimeline": {
            "startSeconds": stage_start,
            "endSeconds": stage_end,
            "clips": clips,
        },
    }


def _build_reuse_receipt(
    *,
    character_class: str,
    skill_id: int,
    stage_index: int,
    stage_count: int,
    nominal_document: dict[str, Any],
    nominal_receipt: dict[str, Any],
    reused_stage_index: int,
    reused_document: dict[str, Any],
    reused_receipt: dict[str, Any],
) -> tuple[Path, dict[str, Any]]:
    identity = (character_class, skill_id, stage_index)
    contract = REUSED_PRODUCT_STAGE_CONTRACTS.get(identity)
    if contract is None or stage_count != contract["stageCount"]:
        raise ValueError("Product-target reuse is not allowlisted for this exact stage.")
    if reused_stage_index != contract["reusedStageIndex"]:
        raise ValueError("Product-target reuse points at the wrong stage.")
    clips = _require_array(
        _require_object(
            nominal_receipt.get("sourceTimeline"), "nominal sourceTimeline"
        ).get("clips"),
        "nominal sourceTimeline.clips",
    )
    if (
        len(clips) != 1
        or not isinstance(clips[0], dict)
        or clips[0].get("clip") != contract["clip"]
    ):
        raise ValueError("Product-target reuse source clip drifted.")
    nominal_equivalence = _require_object(
        nominal_receipt.get("sourceCarrierEquivalence"),
        "nominal sourceCarrierEquivalence",
    )
    reused_equivalence = _require_object(
        reused_receipt.get("sourceCarrierEquivalence"),
        "reused sourceCarrierEquivalence",
    )
    expected_hash = contract["normalizedSourceCarrierSha256"]
    expected_count = contract["sourceCarrierCount"]
    if (
        nominal_equivalence.get("elementCount") != expected_count
        or reused_equivalence.get("elementCount") != expected_count
        or nominal_equivalence.get("normalizedContentSha256") != expected_hash
        or reused_equivalence.get("normalizedContentSha256") != expected_hash
    ):
        raise ValueError("Repeated-clip source carrier equivalence proof drifted.")
    nominal_authored_hash = _normalized_authored_document_hash(nominal_document)
    reused_authored_hash = _normalized_authored_document_hash(reused_document)
    if nominal_authored_hash != reused_authored_hash:
        raise ValueError("Repeated-clip Authored output content is not equivalent.")

    reused_target_id = _require_string(
        reused_document.get("effectAssetId"), "reused target Effect ID"
    )
    nominal_target_id = _require_string(
        nominal_document.get("effectAssetId"), "nominal target Effect ID"
    )
    _, reused_target_path, _ = _target_contract(
        character_class, skill_id, reused_stage_index, stage_count
    )
    _, nominal_target_path, nominal_receipt_path = _target_contract(
        character_class, skill_id, stage_index, stage_count
    )
    receipt = copy.deepcopy(nominal_receipt)
    receipt["schema"] = REUSE_RECEIPT_SCHEMA
    receipt["version"] = REUSE_RECEIPT_VERSION
    receipt["nominalTargetEffectAssetId"] = nominal_target_id
    receipt["nominalTargetAuthoringPath"] = _data_relative(nominal_target_path)
    receipt["reusesProductTarget"] = reused_target_id
    receipt["reusedTargetAuthoringPath"] = _data_relative(reused_target_path)
    receipt["normalizedSourceCarrierSha256"] = expected_hash
    receipt["normalizedAuthoredContentSha256"] = nominal_authored_hash
    receipt["reusedTargetDocumentSha256"] = _sha256_json(reused_document)
    receipt["nominalOutputEvidence"] = receipt.pop("output")
    receipt.pop("targetEffectAssetId", None)
    receipt.pop("targetAuthoringPath", None)
    validate_reuse_receipt(receipt, nominal_document, reused_document)
    return nominal_receipt_path, receipt


def validate_reuse_receipt(
    receipt: dict[str, Any],
    nominal_document: dict[str, Any],
    reused_document: dict[str, Any],
) -> None:
    if (
        receipt.get("schema") != REUSE_RECEIPT_SCHEMA
        or receipt.get("version") != REUSE_RECEIPT_VERSION
    ):
        raise ValueError("Approximation reuse receipt schema/version is invalid.")
    identity = (
        receipt.get("characterClass"),
        receipt.get("productSkillId"),
        receipt.get("stageIndex"),
    )
    contract = REUSED_PRODUCT_STAGE_CONTRACTS.get(identity)
    if contract is None:
        raise ValueError("Approximation reuse receipt is not exact-stage allowlisted.")
    nominal_id = _require_string(
        receipt.get("nominalTargetEffectAssetId"), "nominalTargetEffectAssetId"
    )
    reused_id = _require_string(
        receipt.get("reusesProductTarget"), "reusesProductTarget"
    )
    if (
        nominal_document.get("effectAssetId") != nominal_id
        or reused_document.get("effectAssetId") != reused_id
    ):
        raise ValueError("Approximation reuse receipt target identity drifted.")
    if receipt.get("normalizedSourceCarrierSha256") != contract[
        "normalizedSourceCarrierSha256"
    ]:
        raise ValueError("Approximation reuse source equivalence hash drifted.")
    normalized_authored_hash = _normalized_authored_document_hash(nominal_document)
    if (
        normalized_authored_hash
        != _normalized_authored_document_hash(reused_document)
        or receipt.get("normalizedAuthoredContentSha256")
        != normalized_authored_hash
    ):
        raise ValueError("Approximation reuse Authored equivalence hash drifted.")
    if receipt.get("reusedTargetDocumentSha256") != _sha256_json(reused_document):
        raise ValueError("Approximation reused target document hash drifted.")
    nominal_output = _require_object(
        receipt.get("nominalOutputEvidence"), "nominalOutputEvidence"
    )
    if nominal_output.get("documentSha256") != _sha256_json(nominal_document):
        raise ValueError("Approximation nominal output evidence drifted.")
    equivalence = _require_object(
        receipt.get("sourceCarrierEquivalence"), "sourceCarrierEquivalence"
    )
    if (
        equivalence.get("elementCount") != contract["sourceCarrierCount"]
        or equivalence.get("normalizedContentSha256")
        != contract["normalizedSourceCarrierSha256"]
    ):
        raise ValueError("Approximation reuse carrier count/hash drifted.")


def _normalized_generated_refresh_receipt(receipt: dict[str, Any]) -> dict[str, Any]:
    normalized = copy.deepcopy(receipt)
    output = _require_object(normalized.get("output"), "refresh receipt output")
    output["documentSha256"] = "<generated-refresh>"
    for raw_occurrence in _require_array(
        normalized.get("occurrences"), "refresh receipt occurrences"
    ):
        occurrence = _require_object(raw_occurrence, "refresh receipt occurrence")
        candidates = _require_array(
            occurrence.get("candidates"), "refresh receipt candidates"
        )
        for index, raw_candidate in enumerate(candidates):
            candidate = _require_object(raw_candidate, "refresh receipt candidate")
            candidate.pop("standaloneLifetimeDecision", None)
            candidate.pop("standaloneSizeDecision", None)
            candidate.pop("standaloneDrawableResourceDecision", None)
            if candidate.get("selectionDecision") != "selected":
                candidates[index] = {
                    key: copy.deepcopy(candidate.get(key))
                    for key in (
                        "sourceElementId",
                        "sourceOrder",
                        "sourceDocumentKind",
                        "sourceKind",
                        "rendererShape",
                        "conversionEligibility",
                        "reasonCodes",
                        "sourceElementSha256",
                    )
                }
    return normalized


def _legacy_accepted_standard_material(
    source_material: dict[str, Any], resources: list[dict[str, Any]]
) -> dict[str, Any]:
    """Reconstruct the one generated profile shape this migration may replace."""
    source_material_path = _require_string(
        source_material.get("sourceMaterialPath"),
        "legacy accepted-standard sourceMaterialPath",
    )
    textures: list[dict[str, str]] = []
    for raw_resource in resources:
        resource = _require_object(raw_resource, "legacy accepted-standard resource")
        slot_id = _require_string(resource.get("slotId"), "legacy resource slotId")
        asset_id = _require_string(resource.get("assetId"), "legacy resource assetId")
        if Path(asset_id).suffix.casefold() != ".dds":
            continue
        textures.append(
            {
                "name": slot_id,
                "sourceObjectPath": f"{source_material_path}:{slot_id}",
                "assetId": asset_id,
                "addressU": "wrap",
                "addressV": "wrap",
                "colorSpace": "srgb",
                "samplingEvidence": "accepted_standard_approximation.v1",
                "group": slot_id,
            }
        )
    material = copy.deepcopy(source_material)
    material["templateId"] = "effect.standard"
    material["sourceProfile"] = {
        "enabled": True,
        "profileId": (
            "authored.approx.standard."
            + hashlib.sha256(source_material_path.encode("utf-8")).hexdigest()[:16]
        ),
        "runtimeShaderProfileId": STANDARD_MATERIAL_RUNTIME_PROFILE,
        "semanticStatus": "accepted_standard_approximation",
        "parentMaterialPath": source_material_path,
        "textures": textures,
        "scalars": [],
        "vectors": [],
        "staticSwitches": [],
        "dynamicParameterSemantics": [],
        "subUVMode": "none",
    }
    return material


def _normalized_generated_refresh_document(
    document: dict[str, Any],
    receipt: dict[str, Any],
    expected_document: dict[str, Any],
    expected_receipt: dict[str, Any],
) -> dict[str, Any]:
    normalized = copy.deepcopy(document)
    elements_by_id = {
        _require_string(element.get("id"), "refresh Element id"): element
        for element in _require_array(normalized.get("elements"), "refresh Elements")
    }
    expected_elements_by_id = {
        _require_string(element.get("id"), "expected refresh Element id"): element
        for element in _require_array(
            expected_document.get("elements"), "expected refresh Elements"
        )
    }
    expected_candidates_by_target: dict[str, dict[str, Any]] = {}
    for raw_occurrence in _require_array(
        expected_receipt.get("occurrences"), "expected refresh receipt occurrences"
    ):
        occurrence = _require_object(raw_occurrence, "expected refresh occurrence")
        for raw_candidate in _require_array(
            occurrence.get("candidates"), "expected refresh candidates"
        ):
            candidate = _require_object(raw_candidate, "expected refresh candidate")
            if candidate.get("selectionDecision") != "selected":
                continue
            element_id = _require_string(
                candidate.get("targetElementId"), "expected refresh targetElementId"
            )
            if element_id in expected_candidates_by_target:
                raise ValueError("Expected refresh target Element is duplicated.")
            expected_candidates_by_target[element_id] = candidate

    existing_candidates_by_target: dict[str, dict[str, Any]] = {}
    for raw_occurrence in _require_array(
        receipt.get("occurrences"), "refresh receipt occurrences"
    ):
        occurrence = _require_object(raw_occurrence, "refresh receipt occurrence")
        for raw_candidate in _require_array(
            occurrence.get("candidates"), "refresh occurrence candidates"
        ):
            candidate = _require_object(raw_candidate, "refresh candidate")
            if candidate.get("selectionDecision") != "selected":
                continue
            element_id = _require_string(
                candidate.get("targetElementId"), "refresh targetElementId"
            )
            if element_id in existing_candidates_by_target:
                raise ValueError("Existing refresh target Element is duplicated.")
            existing_candidates_by_target[element_id] = candidate
    if set(existing_candidates_by_target) != set(expected_candidates_by_target):
        raise ValueError("Generated refresh changed the selected target Element set.")

    existing_stage_start = _require_number(
        _require_object(
            receipt.get("sourceTimeline"), "existing refresh sourceTimeline"
        ).get("startSeconds"),
        "existing refresh stage start",
        non_negative=True,
    )

    for element_id, candidate in expected_candidates_by_target.items():
        existing_candidate = existing_candidates_by_target[element_id]
        if _normalized_generated_refresh_receipt(
            {
                "occurrences": [{"candidates": [existing_candidate]}],
                "output": {"documentSha256": "0" * 64},
            }
        ) != _normalized_generated_refresh_receipt(
            {
                "occurrences": [{"candidates": [candidate]}],
                "output": {"documentSha256": "0" * 64},
            }
        ):
            raise ValueError("Generated refresh candidate provenance drifted.")
        element = elements_by_id.get(element_id)
        expected_element = expected_elements_by_id.get(element_id)
        if element is None or expected_element is None:
            raise ValueError("Generated refresh target Element is missing.")
        material = _require_object(
            element.get("material"), "generated refresh target material"
        )
        provenance = _require_object(
            candidate.get("materialProvenance"),
            "generated refresh source material provenance",
        )
        material_decision = candidate.get("materialDecision")
        if material_decision == "acceptedStandardApproximation":
            resources = _require_array(
                candidate.get("resources"), "generated refresh resources"
            )
            accepted_material = _accepted_material(
                provenance, "acceptedStandardApproximation", resources
            )
            legacy_material = _legacy_accepted_standard_material(provenance, resources)
            if material != accepted_material and material != legacy_material:
                raise ValueError(
                    "Existing generated approximation differs from both exact reviewed "
                    "accepted-standard material contracts."
                )
        elif material != provenance:
            raise ValueError("Existing source-exact material drifted before refresh.")

        expected_lifetime = _require_object(
            candidate.get("standaloneLifetimeDecision"),
            "expected standalone lifetime decision",
        )
        detail = _require_object(element.get("detail"), "existing refresh detail")
        expected_detail = _require_object(
            expected_element.get("detail"), "expected refresh detail"
        )
        existing_drawable = existing_candidate.get(
            "standaloneDrawableResourceDecision"
        )
        expected_drawable = _require_object(
            candidate.get("standaloneDrawableResourceDecision"),
            "expected standalone drawable resource decision",
        )
        if isinstance(existing_drawable, dict):
            previous_resources = existing_drawable.get("targetResourceBindings")
            previous_use_model_material = (
                existing_drawable.get("targetUseModelMaterial") is True
            )
        else:
            previous_resources = existing_candidate.get("resources")
            previous_use_model_material = (
                expected_drawable.get("sourceUseModelMaterial") is True
                if element.get("kind") == "sprite"
                else False
            )
        existing_mesh_detail = _require_object(
            detail.get("mesh"), "existing refresh Mesh detail"
        )
        if (
            element.get("resources") != previous_resources
            or (existing_mesh_detail.get("useModelMaterial") is True)
            != previous_use_model_material
        ):
            raise ValueError(
                "Existing generated drawable resource decision drifted before refresh."
            )
        timing = _require_object(detail.get("timing"), "existing refresh timing")
        existing_lifetime = existing_candidate.get("standaloneLifetimeDecision")
        if isinstance(existing_lifetime, dict):
            previous_lifetime = _require_number(
                existing_lifetime.get("targetLifeTimeSeconds"),
                "existing standalone target lifetime",
                positive=True,
            )
            previous_start_offset = _require_number(
                existing_lifetime.get("targetStartDelayOffsetSeconds", 0.0),
                "existing standalone target start offset",
                non_negative=True,
            )
        else:
            previous_lifetime = _require_number(
                expected_lifetime.get("sourceElementTimingSeconds"),
                "legacy source Element lifetime",
                positive=True,
            )
            previous_start_offset = 0.0
        source_time = _require_number(
            existing_candidate.get("sourceTimeSeconds"),
            "existing generated sourceTimeSeconds",
            non_negative=True,
        )
        previous_start = (
            max(0.0, source_time - existing_stage_start) + previous_start_offset
        )
        if (
            timing.get("lifeTimeSeconds") != previous_lifetime
            or abs(
                _require_number(
                    timing.get("startDelaySeconds"),
                    "existing generated startDelaySeconds",
                    non_negative=True,
                )
                - previous_start
            )
            > TIMELINE_EPSILON
        ):
            raise ValueError("Existing generated lifetime drifted before refresh.")

        expected_size = _require_object(
            candidate.get("standaloneSizeDecision"),
            "expected standalone size decision",
        )
        transform = _require_object(
            detail.get("transform"), "existing refresh transform"
        )
        linear_lerp = _require_object(
            detail.get("linearLerp"), "existing refresh linearLerp"
        )
        existing_size = existing_candidate.get("standaloneSizeDecision")
        if isinstance(existing_size, dict):
            previous_start_scale = existing_size.get("targetStartScale")
            previous_lerp_enabled = (
                existing_size.get("targetLinearLerpScaleEnabled") is True
            )
            previous_end_scale = existing_size.get("targetEndScale")
        else:
            previous_start_scale = expected_size.get("sourceTransformStartScale")
            previous_lerp_enabled = (
                expected_size.get("sourceLinearLerpScaleEnabled") is True
            )
            previous_end_scale = expected_size.get("sourceTransformEndScale")
        if (
            transform.get("scale") != previous_start_scale
            or (linear_lerp.get("scale") is True) != previous_lerp_enabled
            or linear_lerp.get("endScale") != previous_end_scale
        ):
            raise ValueError("Existing generated scale drifted before refresh.")

        element["material"] = copy.deepcopy(expected_element["material"])
        element["resources"] = copy.deepcopy(expected_element["resources"])
        existing_mesh_detail["useModelMaterial"] = expected_detail["mesh"][
            "useModelMaterial"
        ]
        timing["startDelaySeconds"] = expected_detail["timing"]["startDelaySeconds"]
        timing["lifeTimeSeconds"] = expected_detail["timing"]["lifeTimeSeconds"]
        transform["scale"] = copy.deepcopy(expected_detail["transform"]["scale"])
        linear_lerp["scale"] = expected_detail["linearLerp"]["scale"]
        linear_lerp["endScale"] = copy.deepcopy(
            expected_detail["linearLerp"]["endScale"]
        )
    return normalized


def _validate_refreshable_generated_pair(
    *,
    target_path: Path,
    receipt_path: Path,
    expected_document: dict[str, Any],
    expected_receipt: dict[str, Any],
) -> None:
    existing_document = _load_json(target_path, "existing generated approximation")
    existing_receipt = _load_json(receipt_path, "existing approximation receipt")
    target_effect_id = _require_string(
        expected_document.get("effectAssetId"), "refresh targetEffectAssetId"
    )
    if (
        existing_document.get("schema") != "lostark.effect-authoring"
        or existing_document.get("version") != 12
        or existing_document.get("effectAssetId") != target_effect_id
        or existing_receipt.get("schema") != RECEIPT_SCHEMA
        or existing_receipt.get("version") != RECEIPT_VERSION
        or existing_receipt.get("targetEffectAssetId") != target_effect_id
        or existing_receipt.get("targetAuthoringPath") != _data_relative(target_path)
    ):
        raise ValueError("Existing generated approximation ownership drifted.")
    existing_output = _require_object(
        existing_receipt.get("output"), "existing approximation output"
    )
    if existing_output.get("documentSha256") != _sha256_json(existing_document):
        raise ValueError("Existing generated approximation hash drifted.")
    if (
        _normalized_generated_refresh_document(
            existing_document,
            existing_receipt,
            expected_document,
            expected_receipt,
        )
        != expected_document
    ):
        raise ValueError(
            "Existing approximation differs beyond the reviewed generated-contract refresh."
        )
    if _normalized_generated_refresh_receipt(
        existing_receipt
    ) != _normalized_generated_refresh_receipt(expected_receipt):
        raise ValueError(
            "Existing approximation differs beyond the reviewed generated-contract refresh."
        )


