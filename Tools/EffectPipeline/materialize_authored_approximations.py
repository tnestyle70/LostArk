def _standalone_lifetime_decision(
    element: dict[str, Any], analysis: dict[str, Any]
) -> dict[str, Any]:
    detail = _require_object(element.get("detail"), "lifetime source detail")
    timing = _require_object(detail.get("timing"), "lifetime source timing")
    source_timing = _require_number(
        timing.get("lifeTimeSeconds"), "source Element lifeTimeSeconds", positive=True
    )
    if analysis["sourceDocumentKind"] != "particle":
        return {
            "decision": "sourceStandaloneTimingPreserved",
            "sourceElementTimingSeconds": source_timing,
            "targetStartDelayOffsetSeconds": 0.0,
            "targetLifeTimeSeconds": source_timing,
            "rationale": (
                "The source is already standalone, so its authored carrier lifetime is "
                "preserved without interpreting Cascade emitter timing."
            ),
        }

    recipe = _require_object(element.get("sourceRecipe"), "lifetime sourceRecipe")
    emitter_delay = _require_number(
        recipe.get("emitterDelaySeconds"),
        "source emitterDelaySeconds",
        non_negative=True,
    )
    emitter_duration = _require_number(
        recipe.get("emitterDurationSeconds"),
        "source emitterDurationSeconds",
        non_negative=True,
    )
    emitter_loop_count = _require_int(
        recipe.get("emitterLoopCount"), "source emitterLoopCount"
    )
    bursts = _require_array(recipe.get("bursts"), "source bursts")
    burst_times: list[float] = []
    for index, raw_burst in enumerate(bursts):
        burst = _require_object(raw_burst, f"source burst[{index}]")
        burst_times.append(
            _require_number(
                burst.get("timeSeconds"),
                f"source burst[{index}].timeSeconds",
                non_negative=True,
            )
        )
        _require_int(
            burst.get("countMinimum"),
            f"source burst[{index}].countMinimum",
            positive=True,
        )
        _require_int(
            burst.get("countMaximum"),
            f"source burst[{index}].countMaximum",
            positive=True,
        )

    rate_evidence: list[dict[str, Any]] = []
    rate_maxima: list[float] = []
    rate_scale_maxima: list[float] = []
    lifetime_evidence: list[dict[str, Any]] = []
    lifetime_values: list[float] = []
    lifetime_module_count = 0
    for module_index, raw_module in enumerate(
        _require_array(recipe.get("modules"), "lifetime source modules")
    ):
        module = _require_object(raw_module, f"lifetime source module[{module_index}]")
        class_name = _require_string(
            module.get("className"), f"lifetime source module[{module_index}].className"
        ).casefold()
        is_lifetime_module = _source_class_matches(
            class_name, "particlemodulelifetime"
        )
        if is_lifetime_module:
            lifetime_module_count += 1
        for distribution_index, raw_distribution in enumerate(
            _require_array(
                module.get("distributions"),
                f"lifetime source module[{module_index}].distributions",
            )
        ):
            distribution = _require_object(
                raw_distribution,
                f"lifetime source distribution[{module_index}:{distribution_index}]",
            )
            property_path = _require_string(
                distribution.get("propertyPath"), "lifetime distribution propertyPath"
            )
            leaf = property_path.casefold().rsplit(".", 1)[-1]
            if leaf in {"rate", "spawnrate", "ratescale"}:
                values = _distribution_values(
                    distribution, f"continuous rate distribution {property_path}"
                )
                if not values:
                    continue
                maximum = max(abs(value) for value in values)
                evidence = _distribution_evidence(module, distribution)
                evidence["maximumAbsoluteValue"] = maximum
                rate_evidence.append(evidence)
                if leaf == "ratescale":
                    rate_scale_maxima.append(maximum)
                else:
                    rate_maxima.append(maximum)
            if is_lifetime_module and leaf == "lifetime":
                values = _distribution_values(
                    distribution, f"particle lifetime distribution {property_path}"
                )
                positive_values = [value for value in values if value > 0.0]
                evidence = _distribution_evidence(module, distribution)
                evidence["maximumPositiveSeconds"] = (
                    max(positive_values) if positive_values else 0.0
                )
                lifetime_evidence.append(evidence)
                lifetime_values.extend(positive_values)

    continuous_rate_is_zero = bool(rate_maxima) and (
        max(rate_maxima) <= TIMELINE_EPSILON
        or (bool(rate_scale_maxima) and max(rate_scale_maxima) <= TIMELINE_EPSILON)
    )
    finite_emission = continuous_rate_is_zero and emitter_loop_count > 0
    earliest_burst = min(burst_times) if burst_times else 0.0
    latest_burst = max(burst_times) if burst_times else 0.0
    burst_envelope = (
        max(0, emitter_loop_count - 1) * emitter_duration
        + latest_burst
        - earliest_burst
        if finite_emission and burst_times
        else 0.0
    )
    target_start_offset = emitter_delay + (
        earliest_burst if finite_emission and burst_times else 0.0
    )
    common = {
        "sourceElementTimingSeconds": source_timing,
        "sourceEmitterDelaySeconds": emitter_delay,
        "sourceEmitterDurationSeconds": emitter_duration,
        "sourceEmitterLoopCount": emitter_loop_count,
        "sourceBurstCount": len(bursts),
        "sourceBurstTimesSeconds": burst_times,
        "sourceEarliestBurstSeconds": earliest_burst,
        "sourceLatestBurstSeconds": latest_burst,
        "sourceBurstEnvelopeSeconds": burst_envelope,
        "targetStartDelayOffsetSeconds": target_start_offset,
        "continuousRateEvidence": rate_evidence,
        "continuousRateIsZero": continuous_rate_is_zero,
        "sourceParticleLifetimeEvidence": lifetime_evidence,
    }
    if finite_emission:
        if not lifetime_values:
            particle = _require_object(
                detail.get("particle"), "particle lifetime detail fallback"
            )
            detail_lifetime_values = [
                _require_number(
                    value,
                    f"particle detail lifeTimeSeconds[{index}]",
                    positive=True,
                )
                for index, value in enumerate(
                    _require_array(
                        particle.get("lifeTimeSeconds"),
                        "particle detail lifeTimeSeconds",
                    )
                )
            ]
            if len(detail_lifetime_values) != 2:
                raise ValueError("Particle detail lifetime fallback is incomplete.")
            detail_maximum = max(detail_lifetime_values)
            target_lifetime = burst_envelope + detail_maximum
            return {
                **common,
                "decision": "sourceParticleDetailLifetimeMaximum",
                "sourceLifetimeModulePresent": lifetime_module_count > 0,
                "sourceParticleDetailSha256": strict_materializer.source_element_sha256(
                    particle
                ),
                "sourceParticleDetailLifetimeSeconds": detail_lifetime_values,
                "targetLifeTimeSeconds": target_lifetime,
                "rationale": (
                    "The finite-emission source has no positive decoded "
                    "ParticleModuleLifetime sample. Its positive, hash-pinned Imported "
                    "particle detail lifetime range supplies the conservative maximum. "
                    "Emitter delay and the complete finite burst/loop envelope are "
                    "baked into standalone timing; emitterDuration is never inferred "
                    "as one particle's lifetime."
                ),
            }
        particle_tail = max(lifetime_values)
        target_lifetime = burst_envelope + particle_tail
        return {
            **common,
            "decision": "finiteEmissionParticleLifetimeMaximum",
            "sourceParticleLifetimeMaximumSeconds": particle_tail,
            "targetLifeTimeSeconds": target_lifetime,
            "rationale": (
                "Continuous spawn evaluates to zero under a finite emitter loop, so "
                "the standalone snapshot uses the maximum positive, hash-pinned "
                "ParticleModuleLifetime value plus the finite burst/loop envelope to "
                "preserve the complete visual tail. Emitter delay and the earliest "
                "burst are baked into standalone start delay."
            ),
        }
    common["sourceBurstEnvelopeSeconds"] = 0.0
    common["targetStartDelayOffsetSeconds"] = emitter_delay
    return {
        **common,
        "decision": "continuousEmitterWindowPreserved",
        "sourceParticleLifetimeMaximumSeconds": (
            max(lifetime_values) if lifetime_values else 0.0
        ),
        "targetLifeTimeSeconds": source_timing,
        "rationale": (
            "Continuous emission is present or cannot be proven zero, so the "
            "standalone approximation preserves the Imported emitter visibility "
            "window instead of truncating it to one particle's lifetime. Only the "
            "recipe-local emitter delay is baked into standalone start delay; burst "
            "times do not replace the continuous emission window."
        ),
    }


def _multiply_scale(left: list[float], right: list[float]) -> list[float]:
    return [left[index] * right[index] for index in range(3)]


def _distribution_vector_sample(
    module: dict[str, Any],
    distribution: dict[str, Any],
    *,
    use_last_entry: bool,
) -> dict[str, Any]:
    component_count = _require_int(
        distribution.get("componentCount"), "size distribution componentCount"
    )
    if component_count != 3:
        raise ValueError("Standalone size mapping requires a three-component distribution.")
    operation = _require_int(
        distribution.get("operation"), "size distribution operation"
    )
    if operation not in {1, 2, 3}:
        raise ValueError("Standalone size distribution operation is unsupported.")
    lookup = _require_array(
        distribution.get("lookupTable"), "size distribution lookupTable"
    )
    branch = "minimum"
    if lookup:
        values = [
            _require_number(value, f"size lookup value[{index}]")
            for index, value in enumerate(lookup)
        ]
        chunk_size = _require_int(
            distribution.get("lookupTableChunkSize"),
            "size distribution lookupTableChunkSize",
            positive=True,
        )
        expected_chunk_size = component_count * (2 if operation >= 2 else 1)
        if (
            chunk_size != expected_chunk_size
            or len(values) < 2 + chunk_size
            or (len(values) - 2) % chunk_size != 0
        ):
            raise ValueError("Standalone size lookup payload shape is unsupported.")
        entry_count = (len(values) - 2) // chunk_size
        entry_index = entry_count - 1 if use_last_entry else 0
        offset = 2 + entry_index * chunk_size
        raw_vector = values[offset : offset + component_count]
        sample_source = "lookupTable"
        sample_index = entry_index
    else:
        keys = _require_array(distribution.get("keys"), "size distribution keys")
        if keys:
            key = _require_object(
                keys[-1] if use_last_entry else keys[0], "size distribution key"
            )
            raw_vector = [
                _require_number(value, f"size key minimum[{index}]")
                for index, value in enumerate(
                    _require_array(key.get("minimum"), "size key minimum")
                )
            ][:component_count]
            if len(raw_vector) != component_count:
                raise ValueError("Standalone size key payload is incomplete.")
            sample_source = "keyMinimum"
            sample_index = len(keys) - 1 if use_last_entry else 0
            chunk_size = 0
        else:
            raw_vector = [
                _require_number(value, f"size defaultMinimum[{index}]")
                for index, value in enumerate(
                    _require_array(
                        distribution.get("defaultMinimum"),
                        "size distribution defaultMinimum",
                    )
                )
            ][:component_count]
            if len(raw_vector) != component_count:
                raise ValueError("Standalone size default payload is incomplete.")
            sample_source = "defaultMinimum"
            sample_index = 0
            chunk_size = 0
    return {
        "sourceModuleStableId": _require_string(
            module.get("stableId"), "size sample module stableId"
        ),
        "sourceModuleClassName": _require_string(
            module.get("className"), "size sample module className"
        ),
        "propertyPath": _require_string(
            distribution.get("propertyPath"), "size sample propertyPath"
        ),
        "sourceDistributionSha256": strict_materializer.source_element_sha256(
            distribution
        ),
        "operation": operation,
        "chunkSize": chunk_size,
        "sampleSource": sample_source,
        "sampleIndex": sample_index,
        "rangeBranch": branch,
        "rawSignedVector": raw_vector,
    }


def _positive_size_factor(value: float, *, unit_scale: float) -> float:
    return max(0.01, abs(value) * unit_scale)


def _standalone_size_decision(
    element: dict[str, Any], analysis: dict[str, Any], renderer_kind: str
) -> dict[str, Any]:
    detail = _require_object(element.get("detail"), "size source detail")
    transform = _require_object(detail.get("transform"), "size source transform")
    source_scale = [
        _require_number(value, f"source transform scale[{index}]")
        for index, value in enumerate(
            _require_array(transform.get("scale"), "source transform scale")
        )
    ]
    if len(source_scale) != 3 or any(abs(value) <= TIMELINE_EPSILON for value in source_scale):
        raise ValueError("Source transform scale is zero or has unsupported cardinality.")
    linear_lerp = _require_object(detail.get("linearLerp"), "size source linearLerp")
    source_lerp_enabled = linear_lerp.get("scale") is True
    source_end_scale = [
        _require_number(value, f"source linearLerp endScale[{index}]")
        for index, value in enumerate(
            _require_array(linear_lerp.get("endScale"), "source linearLerp endScale")
        )
    ]
    if len(source_end_scale) != 3:
        raise ValueError("Source linearLerp endScale cardinality is unsupported.")
    if analysis["sourceDocumentKind"] != "particle":
        return {
            "decision": "sourceStandaloneScalePreserved",
            "sourceTransformStartScale": source_scale,
            "sourceLinearLerpScaleEnabled": source_lerp_enabled,
            "sourceTransformEndScale": source_end_scale,
            "targetStartScale": source_scale,
            "targetLinearLerpScaleEnabled": source_lerp_enabled,
            "targetEndScale": source_end_scale,
            "rationale": "The source is already a standalone renderer.",
        }

    particle = _require_object(detail.get("particle"), "source particle detail")
    start_size = [
        _require_number(value, f"source particle startSize[{index}]", non_negative=True)
        for index, value in enumerate(
            _require_array(particle.get("startSize"), "source particle startSize")
        )
    ]
    end_size = [
        _require_number(value, f"source particle endSize[{index}]", non_negative=True)
        for index, value in enumerate(
            _require_array(particle.get("endSize"), "source particle endSize")
        )
    ]
    if len(start_size) != 2 or len(end_size) != 2:
        raise ValueError("Particle size endpoint cardinality is unsupported.")
    recipe = _require_object(element.get("sourceRecipe"), "size sourceRecipe")
    size_module_evidence: list[dict[str, Any]] = []
    evolution_module_evidence: list[dict[str, Any]] = []
    initial_samples: list[dict[str, Any]] = []
    evolution_samples: list[dict[str, Any]] = []
    for module_index, raw_module in enumerate(
        _require_array(recipe.get("modules"), "size source modules")
    ):
        module = _require_object(raw_module, f"size source module[{module_index}]")
        class_name = _require_string(
            module.get("className"), f"size source module[{module_index}].className"
        )
        folded_class = class_name.casefold()
        if "size" not in folded_class:
            continue
        distributions: list[dict[str, Any]] = []
        for raw_distribution in _require_array(
            module.get("distributions"),
            f"size source module[{module_index}].distributions",
        ):
            distribution = _require_object(raw_distribution, "size source distribution")
            evidence = _distribution_evidence(module, distribution)
            distributions.append(evidence)
            property_leaf = evidence["propertyPath"].casefold().rsplit(".", 1)[-1]
            if (
                _source_class_matches(class_name, "particlemodulesize")
                and property_leaf == "startsize"
            ):
                initial_samples.append(
                    _distribution_vector_sample(
                        module, distribution, use_last_entry=False
                    )
                )
            if (
                (
                    "sizemultiplylife" in folded_class
                    and property_leaf == "lifemultiplier"
                )
                or (
                    "sizescalebytime" in folded_class
                    and property_leaf == "sizescalebytime"
                )
            ):
                evolution_samples.append(
                    _distribution_vector_sample(
                        module, distribution, use_last_entry=True
                    )
                )
        module_evidence = {
            "sourceModuleStableId": _require_string(
                module.get("stableId"), "size source module stableId"
            ),
            "sourceModuleClassName": class_name,
            "sourceModuleSha256": strict_materializer.source_element_sha256(module),
            "distributions": distributions,
        }
        size_module_evidence.append(module_evidence)
        if "sizemultiplylife" in folded_class or "sizescalebytime" in folded_class:
            evolution_module_evidence.append(copy.deepcopy(module_evidence))
    raw_initial = [0.0, 0.0, 0.0]
    for sample in initial_samples:
        for index, value in enumerate(sample["rawSignedVector"]):
            raw_initial[index] += value
    if initial_samples and renderer_kind == "mesh":
        mapped_initial_signed = [raw_initial[0], raw_initial[2], raw_initial[1]]
        start_factor = [
            _positive_size_factor(value, unit_scale=0.01)
            for value in mapped_initial_signed
        ]
        axis_mapping = "mesh.raw-xyz-to-client-xzy.centimeters.v1"
        representative_decision = "sourceLookupFirstSampleRepresentative"
    elif initial_samples and renderer_kind == "sprite":
        mapped_initial_signed = [raw_initial[0], raw_initial[1], 1.0]
        start_factor = [
            _positive_size_factor(raw_initial[0], unit_scale=0.01),
            _positive_size_factor(raw_initial[1], unit_scale=0.01),
            1.0,
        ]
        axis_mapping = "sprite.raw-xy-centimeters.preserve-depth.v1"
        representative_decision = "sourceLookupFirstSampleRepresentative"
    elif not initial_samples and renderer_kind == "mesh":
        raw_initial = [start_size[0], start_size[1], 0.5 * sum(start_size)]
        mapped_initial_signed = list(raw_initial)
        start_factor = [
            _positive_size_factor(value, unit_scale=1.0)
            for value in mapped_initial_signed
        ]
        axis_mapping = "mesh.imported-detail-xy-average-depth.runtime-fallback.v1"
        representative_decision = "runtimeParticleDetailFallbackRepresentative"
    elif not initial_samples and renderer_kind == "sprite":
        raw_initial = [start_size[0], start_size[1], 1.0]
        mapped_initial_signed = list(raw_initial)
        start_factor = [
            _positive_size_factor(start_size[0], unit_scale=1.0),
            _positive_size_factor(start_size[1], unit_scale=1.0),
            1.0,
        ]
        axis_mapping = "sprite.imported-detail-xy.runtime-fallback.v1"
        representative_decision = "runtimeParticleDetailFallbackRepresentative"
    else:
        raise ValueError("Unsupported standalone size renderer kind.")

    raw_evolution = [1.0, 1.0, 1.0]
    for sample in evolution_samples:
        for index, value in enumerate(sample["rawSignedVector"]):
            raw_evolution[index] *= value
    if renderer_kind == "mesh":
        mapped_evolution_signed = [
            raw_evolution[0],
            raw_evolution[2],
            raw_evolution[1],
        ]
        end_factor = [
            _positive_size_factor(value, unit_scale=1.0)
            for value in mapped_evolution_signed
        ]
    else:
        mapped_evolution_signed = [raw_evolution[0], raw_evolution[1], 1.0]
        end_factor = [
            _positive_size_factor(raw_evolution[0], unit_scale=1.0),
            _positive_size_factor(raw_evolution[1], unit_scale=1.0),
            1.0,
        ]

    target_start_scale = _multiply_scale(source_scale, start_factor)
    if evolution_module_evidence and not evolution_samples:
        raise ValueError("Size evolution module has no decoded endpoint distribution.")
    has_size_evolution = bool(evolution_samples)
    target_lerp_enabled = source_lerp_enabled or has_size_evolution
    base_end_scale = source_end_scale if source_lerp_enabled else source_scale
    target_end_scale = _multiply_scale(
        base_end_scale,
        (
            _multiply_scale(start_factor, end_factor)
            if has_size_evolution
            else start_factor
        ),
    )
    return {
        "decision": "particleSizeEndpointBake",
        "representativeDecision": representative_decision,
        "axisMapping": axis_mapping,
        "minimumPositiveFactor": 0.01,
        "signedMirrorDisposition": {
            "disposition": "acceptedApproximation",
            "rationale": (
                "Standalone Transform scale requires positive components. The selected "
                "raw sample remains signed evidence, while the baked factor uses abs and "
                "the importer-compatible 0.01 positive floor; source mirror sign is not "
                "claimed as source-exact."
            ),
        },
        "sourceParticleDetailSha256": strict_materializer.source_element_sha256(
            particle
        ),
        "sourceParticleStartSize": start_size,
        "sourceParticleEndSize": end_size,
        "sourceTransformStartScale": source_scale,
        "sourceLinearLerpScaleEnabled": source_lerp_enabled,
        "sourceTransformEndScale": source_end_scale,
        "sourceInitialSizeSamples": initial_samples,
        "sourceInitialSignedVector": raw_initial,
        "sourceInitialMappedSignedVector": mapped_initial_signed,
        "sourceEvolutionSizeSamples": evolution_samples,
        "sourceEvolutionSignedVector": raw_evolution,
        "sourceEvolutionMappedSignedVector": mapped_evolution_signed,
        "sourceSizeModuleEvidence": size_module_evidence,
        "sourceSizeEvolutionModuleEvidence": evolution_module_evidence,
        "targetStartScale": target_start_scale,
        "targetLinearLerpScaleEnabled": target_lerp_enabled,
        "targetEndScale": target_end_scale,
        "rationale": (
            "The runtime sourceRecipe particle path uses raw Sprite X/Y or remapped "
            "Mesh X/Z/Y size after Element world evaluation; only its Imported-detail "
            "fallback synthesizes Mesh depth from the X/Y average. Standalone Mesh/"
            "Sprite ignores particle size, so the selected first complete source sample "
            "is baked into standalone scale. End scale is used only when a hash-pinned "
            "size-over-life module exists and is an explicit linear endpoint "
            "approximation."
        ),
    }


def _selection_score(
    element: dict[str, Any], material_decision: str
) -> dict[str, int]:
    detail = element.get("detail", {})
    transform = detail.get("transform", {}) if isinstance(detail, dict) else {}
    scale = transform.get("scale", []) if isinstance(transform, dict) else []
    finite_scale = [abs(_safe_float(value)) for value in scale if not isinstance(value, bool)]
    scale_prominence = max(finite_scale, default=0.0)
    color = detail.get("color", {}) if isinstance(detail, dict) else {}
    timing = detail.get("timing", {}) if isinstance(detail, dict) else {}
    return {
        "sourceMaterialFidelity": (
            0 if material_decision == "acceptedStandardApproximation" else 1
        ),
        "resourceCount": len(element.get("resources", [])),
        "emissiveMicrounits": int(
            round(max(0.0, _safe_float(color.get("emissiveIntensity"))) * 1_000_000)
        ),
        "scaleMicrounits": int(round(scale_prominence * 1_000_000)),
        "lifetimeMicrounits": int(
            round(
                max(0.0, _safe_float(timing.get("lifeTimeSeconds"))) * 1_000_000
            )
        ),
    }


def _score_sort_key(candidate: dict[str, Any]) -> tuple[int, ...]:
    score = candidate["selectionScore"]
    return (
        -score["sourceMaterialFidelity"],
        -score["resourceCount"],
        -score["emissiveMicrounits"],
        -score["scaleMicrounits"],
        -score["lifetimeMicrounits"],
        candidate["sourceOrder"],
    )


def _source_event_id(element: dict[str, Any]) -> str:
    presentation = element.get("sourcePresentation", {})
    if not isinstance(presentation, dict):
        return ""
    value = presentation.get("sourceEventId", "")
    return value if isinstance(value, str) else ""


def _source_system_id(element: dict[str, Any]) -> str:
    element_id = _require_string(element.get("id"), "source element ID")
    marker = element_id.find(".particle")
    return element_id[:marker] if marker > 0 else ""


def _source_delay(element: dict[str, Any], source_element_id: str) -> float:
    detail = _require_object(element.get("detail"), "source detail")
    timing = _require_object(detail.get("timing"), "source detail.timing")
    return _require_number(
        timing.get("startDelaySeconds"),
        f"source Element timing {source_element_id}",
        non_negative=True,
    )


def _occurrence_key(element: dict[str, Any], delay: float) -> str:
    source_event_id = _source_event_id(element)
    if source_event_id:
        return f"event:{source_event_id}"
    return f"timeline:{delay:.6f}"


def _candidate_record(
    element: dict[str, Any],
    source_order: int,
    group_texture_bindings: dict[str, list[dict[str, Any]]],
    reviewed_renderer_approval: dict[str, Any] | None = None,
    occurrence_event_id: str = "",
) -> tuple[dict[str, Any], str]:
    source_element_id = _require_string(element.get("id"), "source element ID")
    analysis = strict_materializer.analyze_source_element(element)
    source_kind = analysis["sourceKind"]
    if source_kind in {"standaloneMesh", "meshParticle"}:
        renderer_kind = "mesh"
    elif source_kind in {"standaloneSprite", "spriteParticle"}:
        renderer_kind = "sprite"
    else:
        raise ValueError(f"Unsupported source carrier kind: {source_kind}")
    approved_unknown = (
        analysis["conversionEligibility"] == strict_materializer.UNKNOWN
        and reviewed_renderer_approval is not None
        and source_element_id
        in set(reviewed_renderer_approval["sourceElementIds"])
    )
    if analysis["conversionEligibility"] == strict_materializer.UNKNOWN and not approved_unknown:
        raise ValueError("UNKNOWN source conversion eligibility is not selectable.")
    resources = _validate_element_resources(element, source_kind, source_element_id)
    material_decision, raw_material = _validate_source_material(
        element, source_element_id
    )
    (
        conversion_decision,
        source_module_ids,
        removed_modules,
        source_module_evidence,
    ) = _conversion_contract(
        element,
        analysis,
        reviewed_renderer_approximation=approved_unknown,
    )
    lifetime_decision = _standalone_lifetime_decision(element, analysis)
    size_decision = _standalone_size_decision(element, analysis, renderer_kind)
    drawable_resource_decision = _standalone_drawable_resource_decision(
        element,
        renderer_kind,
        resources,
        material_decision,
        group_texture_bindings,
    )
    record = {
        "sourceElementId": source_element_id,
        "sourceOrder": source_order,
        "sourceEventId": _source_event_id(element),
        "occurrenceEventId": occurrence_event_id or _source_event_id(element),
        "sourceTimeSeconds": _source_delay(element, source_element_id),
        "sourceDocumentKind": analysis["sourceDocumentKind"],
        "sourceKind": source_kind,
        "rendererShape": analysis["rendererShape"],
        "conversionEligibility": analysis["conversionEligibility"],
        "reasonCodes": copy.deepcopy(analysis["reasonCodes"]),
        "fidelityWarningCodes": copy.deepcopy(analysis["fidelityWarningCodes"]),
        "fidelityWarnings": copy.deepcopy(analysis["fidelityWarnings"]),
        "sourceElementSha256": strict_materializer.source_element_sha256(element),
        "resources": resources,
        "materialDecision": material_decision,
        "materialProvenance": raw_material,
        "conversionDecision": conversion_decision,
        "sourceModuleStableIds": source_module_ids,
        "sourceModuleEvidence": source_module_evidence,
        "removedModuleDispositions": removed_modules,
        "standaloneLifetimeDecision": lifetime_decision,
        "standaloneSizeDecision": size_decision,
        "standaloneDrawableResourceDecision": drawable_resource_decision,
        "selectionScore": _selection_score(element, material_decision),
        "selectionDecision": "candidate",
    }
    if approved_unknown:
        record["reviewedRendererApproximation"] = {
            "decision": reviewed_renderer_approval["decision"],
            "rationale": reviewed_renderer_approval["rationale"],
            "sourceDocumentSha256": reviewed_renderer_approval[
                "sourceDocumentSha256"
            ],
        }
    return record, renderer_kind


