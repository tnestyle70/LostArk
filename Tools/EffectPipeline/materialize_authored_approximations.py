def evaluate_intake_manifest(
    manifest_path: Path,
    claimed_source_elements: set[tuple[str, str]] | None = None,
    *,
    allow_generated_refresh: bool = False,
) -> tuple[
    list[dict[str, Any]],
    list[tuple[Path, dict[str, Any]]],
    list[tuple[Path, dict[str, Any]]],
]:
    manifest_path = manifest_path.resolve()
    try:
        manifest_path.relative_to(IMPORTED_ROOT)
    except ValueError as error:
        raise ValueError("Combat source-stage manifest escaped Effects/Imported.") from error
    manifest = _load_json(manifest_path, "combat source-stage manifest")
    if manifest.get("schema") != INTAKE_SCHEMA or manifest.get("version") != INTAKE_VERSION:
        raise ValueError("Combat source-stage manifest schema/version is invalid.")
    character_class = _require_string(
        manifest.get("characterClass"), "manifest characterClass"
    )
    if character_class not in CLASS_TOKENS:
        raise ValueError(f"Unsupported characterClass: {character_class}")
    consumer_contract = _require_object(
        manifest.get("consumerContract"), "manifest consumerContract"
    )
    if (
        consumer_contract.get("outerCueRoot") != "Player"
        or consumer_contract.get("outerCueFollow") is not True
        or consumer_contract.get("innerSnapshotFollow") is not False
    ):
        raise ValueError("Source intake consumer contract is not Player-root/follow snapshot.")

    results: list[dict[str, Any]] = []
    outputs: list[tuple[Path, dict[str, Any]]] = []
    receipts: list[tuple[Path, dict[str, Any]]] = []
    if claimed_source_elements is None:
        claimed_source_elements = set()
    seen_skills: set[int] = set()
    seen_targets: set[str] = set()
    for skill_position, raw_skill in enumerate(
        _require_array(manifest.get("skills"), "manifest skills")
    ):
        skill = _require_object(raw_skill, f"skills[{skill_position}]")
        skill_id = _require_int(
            skill.get("productSkillId"),
            f"skills[{skill_position}].productSkillId",
            positive=True,
        )
        if skill_id in seen_skills:
            raise ValueError(f"Duplicate productSkillId: {skill_id}")
        seen_skills.add(skill_id)
        _require_string(skill.get("inputSlot"), f"skills[{skill_position}].inputSlot")
        _require_string(skill.get("skillKind"), f"skills[{skill_position}].skillKind")
        skill_source_ids = [
            _require_int(value, "skill sourceSkillIds[]", positive=True)
            for value in _require_array(
                skill.get("sourceSkillIds"), "skill sourceSkillIds"
            )
        ]
        if len(skill_source_ids) != 1:
            raise ValueError(
                f"Skill {skill_id} must expose exactly one source alias identity."
            )
        stages = [
            _require_object(raw_stage, "skill stage")
            for raw_stage in _require_array(skill.get("stages"), "skill stages")
        ]
        if not stages:
            raise ValueError(f"Skill {skill_id} has no action/combo stages.")
        if [stage.get("stageIndex") for stage in stages] != list(range(len(stages))):
            raise ValueError(f"Skill {skill_id} stage order is not contiguous.")
        built_stage_products: dict[
            int,
            tuple[Path, dict[str, Any], Path, dict[str, Any]],
        ] = {}
        for stage in stages:
            stage_index = _require_int(stage.get("stageIndex"), "stageIndex")
            target_effect_id, target_path, receipt_path = _target_contract(
                character_class, skill_id, stage_index, len(stages)
            )
            if target_effect_id in seen_targets:
                raise ValueError(f"Duplicate target Effect ID: {target_effect_id}")
            seen_targets.add(target_effect_id)
            silent_completion = _validate_intentionally_silent_stage(
                character_class=character_class,
                skill_id=skill_id,
                stage=stage,
                stage_count=len(stages),
            )
            if silent_completion is not None:
                if target_path.exists() or receipt_path.exists():
                    results.append(
                        {
                            "characterClass": character_class,
                            "productSkillId": skill_id,
                            "stageIndex": stage_index,
                            "nominalTargetEffectAssetId": target_effect_id,
                            "status": "blocked",
                            "reason": (
                                "Intentionally-silent stage has a stale Authored output "
                                "or approximation receipt."
                            ),
                        }
                    )
                    continue
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "nominalTargetEffectAssetId": target_effect_id,
                        "status": "sourceIntentionallySilent",
                        "completionDecision": silent_completion,
                    }
                )
                continue
            if target_effect_id in PROTECTED_TARGETS:
                _validate_protected_target(target_path, target_effect_id)
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "targetEffectAssetId": target_effect_id,
                        "status": "preservedExisting",
                        "reason": "Protected reviewed DimensionMaster A baseline.",
                    }
                )
                continue
            if stage.get("status") not in CONSUMABLE_INTAKE_STATUSES:
                blockers = stage.get("blockers", [])
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "targetEffectAssetId": target_effect_id,
                        "status": "blocked",
                        "reason": "Source intake stage is not ready.",
                        "blockers": copy.deepcopy(blockers),
                    }
                )
                continue
            try:
                output_path, document, receipt_path, receipt = build_stage_approximation(
                    character_class=character_class,
                    skill_id=skill_id,
                    stage=stage,
                    stage_count=len(stages),
                    claimed_source_elements=claimed_source_elements,
                )
            except StageBlocked as error:
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "targetEffectAssetId": target_effect_id,
                        "status": "blocked",
                        "reason": str(error),
                    }
                )
                continue
            built_stage_products[stage_index] = (
                output_path,
                document,
                receipt_path,
                receipt,
            )

            reuse_contract = REUSED_PRODUCT_STAGE_CONTRACTS.get(
                (character_class, skill_id, stage_index)
            )
            if reuse_contract is not None:
                reused_stage_index = reuse_contract["reusedStageIndex"]
                reused_product = built_stage_products.get(reused_stage_index)
                if reused_product is None:
                    raise ValueError("Reused product stage was not materialized first.")
                _, reused_document, _, reused_receipt = reused_product
                reuse_receipt_path, reuse_receipt = _build_reuse_receipt(
                    character_class=character_class,
                    skill_id=skill_id,
                    stage_index=stage_index,
                    stage_count=len(stages),
                    nominal_document=document,
                    nominal_receipt=receipt,
                    reused_stage_index=reused_stage_index,
                    reused_document=reused_document,
                    reused_receipt=reused_receipt,
                )
                reused_target_id = reuse_receipt["reusesProductTarget"]
                if target_path.exists():
                    results.append(
                        {
                            "characterClass": character_class,
                            "productSkillId": skill_id,
                            "stageIndex": stage_index,
                            "nominalTargetEffectAssetId": target_effect_id,
                            "reusesProductTarget": reused_target_id,
                            "status": "blocked",
                            "reason": "Reused product stage has a stale nominal Authored target.",
                        }
                    )
                    continue
                reuse_status = "reusesProductTarget"
                if reuse_receipt_path.exists():
                    existing_reuse = _load_json(
                        reuse_receipt_path, "existing approximation reuse receipt"
                    )
                    if existing_reuse != reuse_receipt:
                        if not allow_generated_refresh:
                            results.append(
                                {
                                    "characterClass": character_class,
                                    "productSkillId": skill_id,
                                    "stageIndex": stage_index,
                                    "nominalTargetEffectAssetId": target_effect_id,
                                    "reusesProductTarget": reused_target_id,
                                    "status": "blocked",
                                    "reason": "Existing approximation reuse receipt drifted.",
                                }
                            )
                            continue
                        _validate_refreshable_reuse_receipt(
                            receipt_path=reuse_receipt_path,
                            expected_receipt=reuse_receipt,
                        )
                        receipts.append((reuse_receipt_path, reuse_receipt))
                        reuse_status = "refreshProductReuse"
                    else:
                        reuse_status = "preservedProductReuse"
                else:
                    receipts.append((reuse_receipt_path, reuse_receipt))
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "nominalTargetEffectAssetId": target_effect_id,
                        "reusesProductTarget": reused_target_id,
                        "status": reuse_status,
                        "sourceCarrierCount": reuse_contract["sourceCarrierCount"],
                        "normalizedSourceCarrierSha256": reuse_contract[
                            "normalizedSourceCarrierSha256"
                        ],
                        "normalizedAuthoredContentSha256": reuse_receipt[
                            "normalizedAuthoredContentSha256"
                        ],
                        "receiptPath": _data_relative(reuse_receipt_path),
                    }
                )
                continue

            if target_path.exists() and receipt_path.exists():
                existing_document = _load_json(target_path, "existing Authored approximation")
                existing_receipt = _load_json(
                    receipt_path, "existing approximation receipt"
                )
                if existing_document != document or existing_receipt != receipt:
                    if not allow_generated_refresh:
                        results.append(
                            {
                                "characterClass": character_class,
                                "productSkillId": skill_id,
                                "stageIndex": stage_index,
                                "targetEffectAssetId": target_effect_id,
                                "status": "blocked",
                                "reason": (
                                    "Existing generated approximation drifted from "
                                    "source truth."
                                ),
                            }
                        )
                        continue
                    _validate_refreshable_generated_pair(
                        target_path=target_path,
                        receipt_path=receipt_path,
                        expected_document=document,
                        expected_receipt=receipt,
                    )
                    outputs.append((output_path, document))
                    receipts.append((receipt_path, receipt))
                    results.append(
                        {
                            "characterClass": character_class,
                            "productSkillId": skill_id,
                            "stageIndex": stage_index,
                            "targetEffectAssetId": target_effect_id,
                            "status": "refreshGenerated",
                            "meshCount": receipt["output"]["meshCount"],
                            "spriteCount": receipt["output"]["spriteCount"],
                            "receiptPath": _data_relative(receipt_path),
                        }
                    )
                    continue
                validate_materialized_stage(existing_document, existing_receipt)
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "targetEffectAssetId": target_effect_id,
                        "status": "preservedGenerated",
                        "meshCount": receipt["output"]["meshCount"],
                        "spriteCount": receipt["output"]["spriteCount"],
                        "receiptPath": _data_relative(receipt_path),
                    }
                )
                continue
            if receipt_path.exists() and not target_path.exists():
                results.append(
                    {
                        "characterClass": character_class,
                        "productSkillId": skill_id,
                        "stageIndex": stage_index,
                        "targetEffectAssetId": target_effect_id,
                        "status": "blocked",
                        "reason": "Approximation receipt exists without its Authored target.",
                    }
                )
                continue
            replacement_status = False
            if target_path.exists():
                if target_effect_id in REPLACEABLE_LEGACY_PARTICLE_TARGETS:
                    _validate_replaceable_legacy_particle_target(
                        target_path, target_effect_id
                    )
                    replacement_status = True
                else:
                    results.append(
                        {
                            "characterClass": character_class,
                            "productSkillId": skill_id,
                            "stageIndex": stage_index,
                            "targetEffectAssetId": target_effect_id,
                            "status": "blocked",
                            "reason": (
                                "Authored target already exists and is never "
                                "auto-overwritten."
                            ),
                        }
                    )
                    continue
            outputs.append((output_path, document))
            receipts.append((receipt_path, receipt))
            results.append(
                {
                    "characterClass": character_class,
                    "productSkillId": skill_id,
                    "stageIndex": stage_index,
                    "targetEffectAssetId": target_effect_id,
                    "status": (
                        "replaceLegacyParticle" if replacement_status else "generated"
                    ),
                    "meshCount": receipt["output"]["meshCount"],
                    "spriteCount": receipt["output"]["spriteCount"],
                    "receiptPath": _data_relative(receipt_path),
                }
            )
    return results, outputs, receipts


def materialize_manifests(
    manifest_paths: Iterable[Path],
    *,
    allow_generated_refresh: bool = False,
) -> tuple[
    dict[str, Any],
    list[tuple[Path, dict[str, Any]]],
    list[tuple[Path, dict[str, Any]]],
]:
    paths = [Path(path).resolve() for path in manifest_paths]
    if not paths:
        raise ValueError("No combat source-stage manifests were provided.")
    results: list[dict[str, Any]] = []
    outputs: list[tuple[Path, dict[str, Any]]] = []
    receipts: list[tuple[Path, dict[str, Any]]] = []
    seen_output_paths: set[Path] = set()
    seen_receipt_paths: set[Path] = set()
    claimed_source_elements: set[tuple[str, str]] = set()
    for path in paths:
        manifest_results, manifest_outputs, manifest_receipts = evaluate_intake_manifest(
            path,
            claimed_source_elements,
            allow_generated_refresh=allow_generated_refresh,
        )
        results.extend(manifest_results)
        for output_path, document in manifest_outputs:
            if output_path in seen_output_paths:
                raise ValueError(f"Duplicate Authored output path: {output_path}")
            seen_output_paths.add(output_path)
            outputs.append((output_path, document))
        for receipt_path, receipt in manifest_receipts:
            if receipt_path in seen_receipt_paths:
                raise ValueError(f"Duplicate approximation receipt: {receipt_path}")
            seen_receipt_paths.add(receipt_path)
            receipts.append((receipt_path, receipt))
    status = {
        "schema": STATUS_SCHEMA,
        "version": STATUS_VERSION,
        "selectionRule": SELECTION_RULE,
        "stages": results,
        "summary": {
            "stageCount": len(results),
            "effectBearingStageCount": sum(
                row["status"]
                in {
                    "generated",
                    "replaceLegacyParticle",
                    "preservedExisting",
                    "preservedGenerated",
                    "refreshGenerated",
                    "reusesProductTarget",
                    "preservedProductReuse",
                    "refreshProductReuse",
                }
                for row in results
            ),
            "generatedStageCount": sum(row["status"] == "generated" for row in results),
            "replacedLegacyStageCount": sum(
                row["status"] == "replaceLegacyParticle" for row in results
            ),
            "blockedStageCount": sum(row["status"] == "blocked" for row in results),
            "preservedStageCount": sum(
                row["status"] == "preservedExisting" for row in results
            ),
            "preservedGeneratedStageCount": sum(
                row["status"] == "preservedGenerated" for row in results
            ),
            "refreshedGeneratedStageCount": sum(
                row["status"] == "refreshGenerated" for row in results
            ),
            "reusedProductStageCount": sum(
                row["status"]
                in {
                    "reusesProductTarget",
                    "preservedProductReuse",
                    "refreshProductReuse",
                }
                for row in results
            ),
            "intentionallySilentStageCount": sum(
                row["status"] == "sourceIntentionallySilent" for row in results
            ),
            "uniqueProductTargetCount": sum(
                row["status"]
                in {
                    "generated",
                    "replaceLegacyParticle",
                    "preservedExisting",
                    "preservedGenerated",
                    "refreshGenerated",
                }
                for row in results
            ),
            "pendingAuthoredOutputCount": len(outputs),
            "pendingSelectionReceiptCount": len(receipts),
        },
    }
    return status, outputs, receipts


def build_coverage_manifest(
    status: dict[str, Any], manifest_paths: Iterable[Path]
) -> dict[str, Any]:
    if status.get("schema") != STATUS_SCHEMA or status.get("version") != STATUS_VERSION:
        raise ValueError("Approximation status schema/version is invalid.")
    source_manifests: list[dict[str, str]] = []
    for raw_path in manifest_paths:
        path = Path(raw_path).resolve()
        try:
            path.relative_to(IMPORTED_ROOT)
        except ValueError as error:
            raise ValueError("Coverage source manifest escaped Effects/Imported.") from error
        source_manifests.append(
            {
                "path": _data_relative(path),
                "sha256": _sha256_file(path),
            }
        )
    source_manifests.sort(key=lambda row: row["path"])

    normalized_stages: list[dict[str, Any]] = []
    product_target_ids: set[str] = set()
    selection_receipt_count = 0
    generated_target_count = 0
    for raw_stage in _require_array(status.get("stages"), "status stages"):
        stage = _require_object(raw_stage, "status stage")
        stage_status = _require_string(stage.get("status"), "status stage status")
        row: dict[str, Any] = {
            "characterClass": _require_string(
                stage.get("characterClass"), "status characterClass"
            ),
            "productSkillId": _require_int(
                stage.get("productSkillId"), "status productSkillId", positive=True
            ),
            "stageIndex": _require_int(stage.get("stageIndex"), "status stageIndex"),
        }
        if stage_status in {
            "generated",
            "replaceLegacyParticle",
            "preservedGenerated",
            "refreshGenerated",
        }:
            target_id = _require_string(
                stage.get("targetEffectAssetId"), "status targetEffectAssetId"
            )
            row.update(
                {
                    "decision": "authoredProductTarget",
                    "targetEffectAssetId": target_id,
                    "meshCount": _require_int(stage.get("meshCount"), "meshCount"),
                    "spriteCount": _require_int(
                        stage.get("spriteCount"), "spriteCount"
                    ),
                    "receiptPath": _require_string(
                        stage.get("receiptPath"), "status receiptPath"
                    ),
                }
            )
            product_target_ids.add(target_id)
            selection_receipt_count += 1
            generated_target_count += 1
        elif stage_status == "preservedExisting":
            target_id = _require_string(
                stage.get("targetEffectAssetId"), "protected targetEffectAssetId"
            )
            row.update(
                {
                    "decision": "protectedProductTarget",
                    "targetEffectAssetId": target_id,
                }
            )
            product_target_ids.add(target_id)
        elif stage_status in {
            "reusesProductTarget",
            "preservedProductReuse",
            "refreshProductReuse",
        }:
            reused_target_id = _require_string(
                stage.get("reusesProductTarget"), "reusesProductTarget"
            )
            row.update(
                {
                    "decision": "reusesProductTarget",
                    "nominalTargetEffectAssetId": _require_string(
                        stage.get("nominalTargetEffectAssetId"),
                        "nominalTargetEffectAssetId",
                    ),
                    "reusesProductTarget": reused_target_id,
                    "sourceCarrierCount": _require_int(
                        stage.get("sourceCarrierCount"),
                        "sourceCarrierCount",
                        positive=True,
                    ),
                    "normalizedSourceCarrierSha256": _require_sha256(
                        stage.get("normalizedSourceCarrierSha256"),
                        "normalizedSourceCarrierSha256",
                    ),
                    "normalizedAuthoredContentSha256": _require_sha256(
                        stage.get("normalizedAuthoredContentSha256"),
                        "normalizedAuthoredContentSha256",
                    ),
                    "receiptPath": _require_string(
                        stage.get("receiptPath"), "reuse receiptPath"
                    ),
                }
            )
            product_target_ids.add(reused_target_id)
            selection_receipt_count += 1
        elif stage_status == "sourceIntentionallySilent":
            row.update(
                {
                    "decision": "sourceIntentionallySilent",
                    "nominalTargetEffectAssetId": _require_string(
                        stage.get("nominalTargetEffectAssetId"),
                        "silent nominalTargetEffectAssetId",
                    ),
                    "completionDecision": copy.deepcopy(
                        _require_object(
                            stage.get("completionDecision"),
                            "silent completionDecision",
                        )
                    ),
                }
            )
        elif stage_status == "blocked":
            row.update(
                {
                    "decision": "blocked",
                    "reason": _require_string(stage.get("reason"), "blocked reason"),
                }
            )
        else:
            raise ValueError(f"Unsupported coverage stage status: {stage_status}")
        normalized_stages.append(row)

    coverage = {
        "schema": COVERAGE_SCHEMA,
        "version": COVERAGE_VERSION,
        "selectionRule": SELECTION_RULE,
        "sourceManifests": source_manifests,
        "stages": normalized_stages,
        "summary": {
            "stageCount": len(normalized_stages),
            "effectBearingStageCount": sum(
                row["decision"]
                in {
                    "authoredProductTarget",
                    "protectedProductTarget",
                    "reusesProductTarget",
                }
                for row in normalized_stages
            ),
            "intentionallySilentStageCount": sum(
                row["decision"] == "sourceIntentionallySilent"
                for row in normalized_stages
            ),
            "blockedStageCount": sum(
                row["decision"] == "blocked" for row in normalized_stages
            ),
            "uniqueProductTargetCount": len(product_target_ids),
            "generatedApproximationTargetCount": generated_target_count,
            "protectedProductTargetCount": sum(
                row["decision"] == "protectedProductTarget"
                for row in normalized_stages
            ),
            "reusedProductStageCount": sum(
                row["decision"] == "reusesProductTarget"
                for row in normalized_stages
            ),
            "selectionReceiptCount": selection_receipt_count,
        },
    }
    return coverage


def _normalized_material_refresh_coverage(
    coverage: dict[str, Any]
) -> dict[str, Any]:
    normalized = copy.deepcopy(coverage)
    for raw_stage in _require_array(normalized.get("stages"), "coverage stages"):
        stage = _require_object(raw_stage, "coverage stage")
        if stage.get("decision") == "reusesProductTarget":
            stage["normalizedAuthoredContentSha256"] = "<generated-refresh>"
    return normalized


def _stage_coverage_for_write(
    coverage: dict[str, Any],
    *,
    allow_generated_refresh: bool = False,
) -> list[tuple[Path, dict[str, Any]]]:
    path = RECEIPT_ROOT / COVERAGE_FILE_NAME
    if path.exists():
        existing = _load_json(path, "existing approximation coverage")
        if existing != coverage:
            if not allow_generated_refresh or _normalized_material_refresh_coverage(
                existing
            ) != _normalized_material_refresh_coverage(coverage):
                raise ValueError("Existing approximation coverage drifted from source truth.")
            return [(path, coverage)]
        return []
    return [(path, coverage)]


def write_outputs_transactionally(
    outputs: Iterable[tuple[Path, dict[str, Any]]],
    receipts: Iterable[tuple[Path, dict[str, Any]]],
    *,
    allow_generated_refresh: bool = False,
) -> None:
    output_rows = list(outputs)
    receipt_rows = list(receipts)
    staged_rows = output_rows + receipt_rows
    if not staged_rows:
        return
    replaceable_paths: set[Path] = set()
    output_paths = {path for path, _ in output_rows}
    expected_receipts_by_target = {
        receipt.get("targetEffectAssetId"): (path, receipt)
        for path, receipt in receipt_rows
        if receipt.get("schema") == RECEIPT_SCHEMA
    }
    for path, document in staged_rows:
        if path.exists() and path in output_paths:
            target_effect_id = _require_string(
                document.get("effectAssetId"), "write output effectAssetId"
            )
            if target_effect_id in REPLACEABLE_LEGACY_PARTICLE_TARGETS:
                expected_pair = expected_receipts_by_target.get(target_effect_id)
                if allow_generated_refresh and expected_pair is not None and expected_pair[
                    0
                ].exists():
                    _validate_refreshable_generated_pair(
                        target_path=path,
                        receipt_path=expected_pair[0],
                        expected_document=document,
                        expected_receipt=expected_pair[1],
                    )
                    replaceable_paths.add(expected_pair[0])
                else:
                    _validate_replaceable_legacy_particle_target(path, target_effect_id)
                replaceable_paths.add(path)
            elif allow_generated_refresh:
                expected_pair = expected_receipts_by_target.get(target_effect_id)
                if expected_pair is None or not expected_pair[0].is_file():
                    raise FileExistsError(
                        "Generated refresh target lacks its matching staged receipt: "
                        f"{path}"
                    )
                _validate_refreshable_generated_pair(
                    target_path=path,
                    receipt_path=expected_pair[0],
                    expected_document=document,
                    expected_receipt=expected_pair[1],
                )
                replaceable_paths.update({path, expected_pair[0]})
            else:
                raise FileExistsError(
                    f"Refusing to overwrite authored output outside the legacy allowlist: {path}"
                )
        elif path.exists():
            if not allow_generated_refresh:
                raise FileExistsError(
                    f"Refusing to overwrite authored evidence/output: {path}"
                )
            schema = document.get("schema")
            if schema == RECEIPT_SCHEMA:
                if path not in replaceable_paths:
                    raise FileExistsError(
                        f"Refresh receipt has no validated Authored pair: {path}"
                    )
            elif schema == REUSE_RECEIPT_SCHEMA:
                _validate_refreshable_reuse_receipt(
                    receipt_path=path,
                    expected_receipt=document,
                )
                replaceable_paths.add(path)
            elif schema == COVERAGE_SCHEMA:
                existing_coverage = _load_json(path, "existing approximation coverage")
                if _normalized_material_refresh_coverage(
                    existing_coverage
                ) != _normalized_material_refresh_coverage(document):
                    raise ValueError("Coverage differs beyond the material refresh.")
                replaceable_paths.add(path)
            else:
                raise FileExistsError(
                    f"Refusing to refresh unowned authored evidence/output: {path}"
                )
        path.parent.mkdir(parents=True, exist_ok=True)
    temporary_paths: list[tuple[Path, Path]] = []
    committed_paths: list[Path] = []
    backup_paths: list[tuple[Path, Path]] = []
    try:
        for target_path, document in staged_rows:
            descriptor, temporary_name = tempfile.mkstemp(
                prefix=f".{target_path.name}.",
                suffix=".tmp",
                dir=target_path.parent,
                text=True,
            )
            temporary_path = Path(temporary_name)
            try:
                with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
                    json.dump(document, stream, ensure_ascii=False, indent=2)
                    stream.write("\n")
            except Exception:
                temporary_path.unlink(missing_ok=True)
                raise
            temporary_paths.append((temporary_path, target_path))
        for target_path in sorted(replaceable_paths):
            descriptor, backup_name = tempfile.mkstemp(
                prefix=f".{target_path.name}.",
                suffix=".generated-backup",
                dir=target_path.parent,
            )
            os.close(descriptor)
            backup_path = Path(backup_name)
            backup_path.unlink()
            os.replace(target_path, backup_path)
            backup_paths.append((backup_path, target_path))
        for temporary_path, target_path in temporary_paths:
            os.replace(temporary_path, target_path)
            committed_paths.append(target_path)
    except Exception:
        for temporary_path, _ in temporary_paths:
            temporary_path.unlink(missing_ok=True)
        for committed_path in committed_paths:
            committed_path.unlink(missing_ok=True)
        for backup_path, target_path in reversed(backup_paths):
            if backup_path.exists():
                os.replace(backup_path, target_path)
        raise
    for backup_path, _ in backup_paths:
        backup_path.unlink(missing_ok=True)


def _default_manifest_paths() -> list[Path]:
    paths: list[Path] = []
    for _, class_directory in CLASS_TOKENS.values():
        candidate = IMPORTED_ROOT / class_directory / (
            f"{class_directory}.combat-source-stage-manifest.json"
        )
        if candidate.is_file():
            paths.append(candidate)
    return paths


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--stage-manifest",
        action="append",
        type=Path,
        default=[],
        help="Combat source-stage manifest. Repeat for multiple classes.",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="Write only missing Authored documents and selection receipts.",
    )
    parser.add_argument(
        "--refresh-generated",
        action="store_true",
        help=(
            "Refresh only hash-owned generated outputs that match the exact prior "
            "contract and migrate reviewed material, carrier timing, and size decisions."
        ),
    )
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    manifest_paths = args.stage_manifest or _default_manifest_paths()
    status, outputs, receipts = materialize_manifests(
        manifest_paths,
        allow_generated_refresh=args.refresh_generated,
    )
    coverage = build_coverage_manifest(status, manifest_paths)
    coverage_rows = _stage_coverage_for_write(
        coverage,
        allow_generated_refresh=args.refresh_generated,
    )
    status["coverageManifestPath"] = _data_relative(
        RECEIPT_ROOT / COVERAGE_FILE_NAME
    )
    if args.write:
        if status["summary"]["blockedStageCount"] != 0:
            raise ValueError("Refusing to write while approximation stages are blocked.")
        write_outputs_transactionally(
            outputs,
            receipts + coverage_rows,
            allow_generated_refresh=args.refresh_generated,
        )
        status["summary"]["writtenAuthoredOutputCount"] = len(outputs)
        status["summary"]["writtenSelectionReceiptCount"] = len(receipts)
        status["summary"]["writtenCoverageManifestCount"] = len(coverage_rows)
    print(json.dumps(status, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
